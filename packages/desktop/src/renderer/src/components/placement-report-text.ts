function row(cells: readonly string[], tag: 'td' | 'th' = 'td'): string {
  return `<tr>${cells.map((cell) => `<${tag}>${escapeHtml(cell)}</${tag}>`).join('')}</tr>`;
}

/**
 * Таблица 1 приложения № 1: нормы обеспечения переносными огнетушителями.
 *
 * Категория пишется один раз на группу строк, как в самом приложении: иначе
 * таблица перестаёт быть узнаваемой рядом с оригиналом.
 */
export function table1Html(): string {
  const rows: string[] = [];
  let previous = '';
  for (const norm of TABLE_1) {
    const first = norm.row === previous ? '' : norm.row;
    previous = norm.row;
    rows.push(row([first, norm.fireClass, norm.asPrinted]));
  }

  return '<h3>Таблица 1. Нормы обеспечения переносными огнетушителями объектов защиты в зависимости '
    + 'от их категорий по пожарной и взрывопожарной опасности и класса пожара</h3>'
    + '<table><thead>'
    + row(['Категория помещения по пожарной и взрывопожарной опасности', 'Класс пожара',
      'Огнетушители с рангом тушения модельного очага'], 'th')
    + `</thead><tbody>${rows.join('')}</tbody></table>`;
}

/** Таблица 2 приложения № 2: нормы оснащения передвижными огнетушителями. */
export function table2Html(): string {
  const rows: string[] = [];
  let previous = '';
  for (const norm of TABLE_2) {
    const first = norm.row === previous ? '' : norm.row;
    const area = norm.row === previous ? '' : String(norm.limitAreaM2);
    previous = norm.row;
    const options = norm.options.map((option) => `${option.count} - ${option.rank}`).join(' или ');
    rows.push(row([first, area, norm.fireClass, options]));
  }

  return '<h3>Таблица 2. Нормы оснащения помещений передвижными огнетушителями</h3>'
    + '<table><thead>'
    + row(['Категория помещения по пожарной и взрывопожарной опасности',
      'Предельная защищаемая площадь, кв. м', 'Класс пожара',
      'Количество огнетушителей с рангом тушения модельного очага, не менее штук'], 'th')
    + `</thead><tbody>${rows.join('')}</tbody></table>`;
}
