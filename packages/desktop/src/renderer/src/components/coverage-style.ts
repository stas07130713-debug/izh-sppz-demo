/**
 * Как выглядит зона покрытия — одно описание на экран и на выгрузку.
 *
 * Заказчик (пункт 1 перечня доработок): «круги зон обслуживания/покрытия
 * огнетушителей должны отображаться со штриховкой в том же виде, в котором они
 * отображаются непосредственно на плане в программе… цвет, толщина линий,
 * штриховка, размер значка и основные принципы отображения должны максимально
 * соответствовать экранному отображению».
 *
 * Прежде вид задавался дважды: на экране — разметкой плана, в приложении к
 * справке — рисованием на холсте, и там круги были синие пунктирные без всякой
 * штриховки. Совпасть два описания могли только случайно.
 *
 * Поэтому числа и цвета живут здесь, а рисуют их двое: разметка плана и холст
 * схемы. Поменять вид — значит поменять это описание, а не два места.
 *
 * Смысл значений:
 *
 *  — цвет один на все круги. Круг нормы одинаков для всех, и красить
 *    незачтённый в серый значило бы окрасить половину плана там, где просто не
 *    заполнены карточки;
 *  — зачтённый обведён сплошной линией, незачтённый пунктиром;
 *  — штриховка вместо сплошной заливки: круги накладываются друг на друга, и
 *    сплошная краска в три слоя закрывает чертёж. Сквозь штриховку планировка
 *    видна, а перекрытие читается как более частая сетка;
 *  — у незачтённого штриховка реже: круг остаётся кругом нормы, а что он не в
 *    счёт — сказано пунктиром и словами в перечне выводов.
 */

/** Цвет круга нормы и его штриховки. */
export const COVERAGE_COLOR = '#ea580c';

/** Цвет точки, до которой огнетушитель не достаёт. */
export const GAP_COLOR = '#dc2626';
export const GAP_RADIUS_PX = 4;
