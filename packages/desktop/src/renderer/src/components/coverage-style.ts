/** Штриховка круга: шаг сетки, толщина штриха и его прозрачность. */
export interface CoverageHatch {
  readonly stepPx: number;
  readonly widthPx: number;
  readonly opacity: number;
}

/**
 * Зачтённый огнетушитель.
 *
 * Штриховка сильно разрежена против прежней. Заказчик: «проверка расстановки
 * вообще ерунду показывает». На деле она считала верно, а показывала так, что
 * смотреть было не на что: круг нормы в двадцать метров на плане этажа шириной
 * тридцать пять метров накрывает лист целиком, и при прежней сетке (шаг 8 при
 * толщине 3 и плотности 0,55 — пятая часть площади в краске) чертёж под ней
 * пропадал. Человек нажимал «проверить» и получал оранжевое полотно вместо
 * плана.
 *
 * Теперь в краске около трёх сотых площади: штриховка читается как заливка,
 * планировка сквозь неё видна, а перекрытие кругов по-прежнему заметно более
 * частой сеткой. Шаг оставлен достаточно мелким, чтобы штрих не пропадал на
 * плане в две тысячи точек, ужатом до ширины окна.
 */
export const COVERAGE_HATCH_COUNTED: CoverageHatch = { stepPx: 11, widthPx: 2.1, opacity: 0.46 };

/** Незачтённый: та же штриховка, только реже. */
export const COVERAGE_HATCH_UNCOUNTED: CoverageHatch = { stepPx: 16, widthPx: 1.8, opacity: 0.34 };

export function coverageHatch(counted: boolean): CoverageHatch {
  return counted ? COVERAGE_HATCH_COUNTED : COVERAGE_HATCH_UNCOUNTED;
}

