/**
 * Масштаб плана в записи «М 1:200» (ТЗ, Дополнение 6, часть С93).
 *
 * Заказчик: «сделай, чтобы при установке масштаба внизу каждого плана выводился
 * масштаб типа 1:200 и т. п.».
 *
 * Проверяется само отношение и то, что оно не появляется там, где его считать
 * не из чего: без масштаба подложки запись «1:200» была бы выдумкой.
 */

import { describe, expect, it } from 'vitest';
import { MM_PER_CSS_PX, formatScale, roundRatio, screenScaleRatio } from './plan-scale';

describe('масштаб показанного плана', () => {
  it('считает отношение действительности к показанному', () => {
    // План шириной 1000 точек по 0,05 м в точке — это 50 м в натуре.
    // Показан шириной 1000 точек CSS, то есть 264,6 мм.
    const ratio = screenScaleRatio(0.05, 1000, 1000);
    expect(ratio).toBeCloseTo(50_000 / (1000 * MM_PER_CSS_PX), 6);
    expect(Math.round(ratio ?? 0)).toBe(189);
  });

  it('приближение делает масштаб крупнее', () => {
    // Тот же план, показанный вдвое шире, — вдвое крупнее.
    const обычно = screenScaleRatio(0.05, 1000, 1000) ?? 0;
    const вдвое = screenScaleRatio(0.05, 1000, 2000) ?? 0;
    expect(вдвое).toBeCloseTo(обычно / 2, 6);
  });

  it('без масштаба подложки ничего не считается', () => {
    expect(screenScaleRatio(null, 1000, 1000)).toBeNull();
    expect(formatScale(null, 1000, 1000)).toBe('');
  });

  it('до отрисовки ничего не считается', () => {
    // Ширина нулевая, пока план не показан: делить на неё нельзя.
    expect(screenScaleRatio(0.05, 1000, 0)).toBeNull();
    expect(screenScaleRatio(0.05, 0, 1000)).toBeNull();
  });

  it('отрицательный и нулевой масштаб не считается', () => {
    expect(screenScaleRatio(0, 1000, 1000)).toBeNull();
    expect(screenScaleRatio(-0.05, 1000, 1000)).toBeNull();
  });
});

describe('округление отношения', () => {
  it('оставляет две значащие цифры', () => {
    expect(roundRatio(189)).toBe(190);
    expect(roundRatio(317)).toBe(320);
    expect(roundRatio(1963)).toBe(2000);
    expect(roundRatio(204)).toBe(200);
  });

  it('мелкие значения оставляет целыми', () => {
    expect(roundRatio(7.4)).toBe(7);
    expect(roundRatio(0.3)).toBe(1);
  });

  it('ровное значение не портит', () => {
    expect(roundRatio(200)).toBe(200);
    expect(roundRatio(50)).toBe(50);
  });
});

describe('запись масштаба', () => {
  it('пишется привычно и с оговоркой о приблизительности', () => {
    // Точка CSS считается по стандартным 96 на дюйм, а у монитора их бывает
    // 92 или 110: обещать точное отношение нельзя.
    expect(formatScale(0.05, 1000, 1000)).toBe('М ≈ 1:190');
  });

  it('разряды не разделяются: на чертежах пишут «1:2000»', () => {
    expect(formatScale(0.5, 1000, 1000)).toBe('М ≈ 1:1900');
  });
});

describe('план ещё не показан', () => {
  /*
   * Найдено на стенде: пока план не отрисован, наблюдаемая ширина равна
   * толщине рамки — две точки, — и подпись обещала «1:74000» там, где на самом
   * деле «1:250». Неверный масштаб на плане хуже, чем никакого: по нему на
   * глаз прикидывают расстояния.
   */
  it('при негодной ширине подписи нет', () => {
    expect(formatScale(0.0985, 400, 2)).toBe('');
    expect(screenScaleRatio(0.0985, 400, 2)).toBeNull();
  });

  it('при рабочей ширине подпись обычная', () => {
    expect(formatScale(0.0985, 400, 592)).toBe('М ≈ 1:250');
  });
});
