/**
 * Пометка непригодных листов при переносе журнала (ТЗ, Дополнение 6, С97).
 *
 * Заказчик: «если строки в загруженном журнале пустые, нужно сразу предупредить
 * — как-то выделить это ещё на этапе выбора».
 *
 * Проверяется правило годности: лист годен, когда у него есть и заголовки, и
 * хоть одна строка данных. Ошибка здесь дорогая в обе стороны — предложить
 * пустой лист значит провести человека через сопоставление колонок впустую, а
 * отвергнуть годный значит потерять раздел журнала молча.
 */

import { describe, expect, it } from 'vitest';
import { isImportable, type SheetInfo } from './ImportSheetPicker';

const sheet = (patch: Partial<SheetInfo>): SheetInfo => ({
  name: 'Лист', dataRows: 10, headerRow: 0, ...patch,
});

describe('годность листа к переносу', () => {
  it('лист с заголовками и строками годен', () => {
    expect(isImportable(sheet({}))).toBe(true);
  });

  it('лист без строк не годен', () => {
    // Заготовка с шапкой, но без записей: сопоставлять колонки не для чего.
    expect(isImportable(sheet({ dataRows: 0 }))).toBe(false);
  });

  it('лист без заголовков не годен', () => {
    // Инструкция или лист с подписями: это не таблица учёта.
    expect(isImportable(sheet({ headerRow: null }))).toBe(false);
  });

  it('заголовки в первой строке — это ноль, а не пустое значение', () => {
    // Ноль обязан считаться найденной строкой: иначе самый обычный лист,
    // где шапка сверху, объявлялся бы непригодным.
    expect(isImportable(sheet({ headerRow: 0, dataRows: 3 }))).toBe(true);
  });

  it('одной строки данных достаточно', () => {
    expect(isImportable(sheet({ dataRows: 1 }))).toBe(true);
  });
});
