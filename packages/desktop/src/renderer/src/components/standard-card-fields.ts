/**
 * Что карточка любого элемента спрашивает без всяких настроек.
 *
 * Заказчик о конструкторе своего вида: «нужно показывать стандартные поля для
 * заполнения карточки + предлагать создать собственные».
 *
 * И это правильно: раньше конструктор молча говорил «учётный номер, изготовитель,
 * дата ввода в эксплуатацию и ответственный есть у всякого оборудования — их
 * заводить не нужно», а какие именно поля будут в карточке, человек узнавал
 * только после того, как заводил вид и ставил первый элемент на план. Заводили
 * лишние поля-двойники: «Инв. №», «Изготовитель», «Примечание».
 *
 * Перечень собран по разметке карточки (`ObjectDetailsForm`) — той её части,
 * которая не зависит от вида оборудования. Он показывается, а не задаётся:
 * убрать стандартное поле нельзя, потому что на нём держатся журнал, заявка и
 * печатные формы — в них эти графы есть у любого оборудования.
 */

export interface StandardCardField {
  readonly title: string;
  /** Короткое пояснение: чтобы не заводили своё поле о том же. */
  readonly hint: string;
}

