/**
 * Свои значки для встроенных видов оборудования (движок E4).
 *
 * Заказчик: «нужно сделать возможность пользователю самостоятельно менять и
 * назначать значки на системы, какие ему будет удобно». Обозначения на планах у
 * предприятий свои — принятые в проектной документации или в инструкциях, — и
 * навязывать наши незачем.
 *
 * Хранятся замены в настройках, а здесь лежит их рабочий список: значок берут
 * из полусотни мест — план, библиотека, журнал, дашборд, — и передавать
 * настройки в каждое значило бы переписать половину окна. Список заполняется
 * там же, где прочитаны настройки, — при запуске и после каждого сохранения.
 *
 * Своих видов это не касается: у них картинка лежит в описании самого вида.
 */

let overrides: Readonly<Record<string, string>> = {};

/** Заменяет список целиком: настройки приходят одним документом. */
export function setElementIconOverrides(next: Readonly<Record<string, string>>): void {
  overrides = next;
}

/** Своя картинка вида или `null`, если вид рисуется встроенным значком. */
export function elementIconOverride(typeCode: string): string | null {
  return overrides[typeCode] ?? null;
}
