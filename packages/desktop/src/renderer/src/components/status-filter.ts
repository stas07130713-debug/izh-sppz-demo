/**
 * Переход «показатель дашборда → отфильтрованный журнал».
 *
 * Сами метки состояния живут в ядре (`filter-tags`): по ним считают и полоса
 * отбора, и строки журнала, и плитки дашборда, и разойтись они не должны.
 * Здесь остаётся то, что относится только к переходу между экранами.
 */

export {
  FILTER_TAG_LABELS,
  FILTER_TAG_ORDER,
  conditionFilterTags,
  matchesFilterTags,
  type FilterTag,
} from '@izh/core';

import type { FilterTag } from '@izh/core';

/**
 * Переход «показатель → отфильтрованный список» (ТЗ, Дополнение 3, часть К4).
 *
 * `typeCode: null` — не переключать вкладку вида оборудования, оставить как
 * есть (для клика по показателю состояния, который не привязан к виду).
 * Пустой `statusTags` — не менять фильтр состояния (для клика по виду
 * системы, который не привязан к статусу). Заданное значение — не переключатель,
 * а установка: журнал должен показать ровно то, что показал показатель, а не
 * добавить условие к тому, что там уже было выбрано руками.
 */
export interface JournalIntent {
  readonly typeCode: string | null;
  readonly statusTags: ReadonlySet<FilterTag>;
  /**
   * Перейти заодно на другой узел дерева.
   *
   * Нужен блоку «Состояние по объектам»: там показаны чужие уровни, и
   * открыть журнал по строке, не сменив узел, значило бы показать не то,
   * на что нажали. Не задан — уровень остаётся прежним.
   */
  readonly nodeId?: string | null;
}
