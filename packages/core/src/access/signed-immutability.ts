/**
 * Подписанное не меняют молча.
 *
 * Заказчик: «после подписания простой электронной подписью внесение изменений
 * невозможно. После внесения изменений необходимо заново подписывать. Если так,
 * то сделай эту логику обязательно».
 *
 * Так и должно быть по закону. Простая электронная подпись подтверждает, что
 * документ подписан **этим** человеком (63-ФЗ, статья 9 часть 1). Подпись
 * относится к содержимому: в ней хранится отпечаток подписанного. Изменить
 * содержимое, оставив прежнюю подпись, — значит выдать чужое согласие за
 * согласие с новым текстом; такая запись перестаёт быть подписанной, даже если
 * подпись в ней формально осталась.
 *
 * Поэтому правило простое и без исключений:
 *
 *  1. подписанную запись изменить нельзя;
 *  2. изменить её можно только вместе с новой подписью — тогда подписывающий
 *     отвечает за новое содержимое;
 *  3. снять подпись, не меняя ничего, тоже нельзя: подпись — не пометка,
 *     которую ставят и убирают, а свидетельство.
 *
 * Сверка отпечатка (`checkSignature`) отвечает на другой вопрос — «не менялось
 * ли подписанное». Она нужна и остаётся: программу могут обойти, правя файл
 * базы снаружи. Здесь же — запрет на изменение изнутри программы.
 */

import type { MaintenanceEvent } from '@izh/contracts';
import { signedJournalContent } from './signed-content.js';

/** Чем закончилась проверка допустимости замены. */
export type ReplacementVerdict =
  /** Прежней записи нет — это заведение новой. */
  | 'новая запись'
  /** Прежняя не подписана: правка допустима. */
  | 'не подписана'
  /** Подписана, но содержимое не менялось: правка служебного допустима. */
  | 'содержимое то же'
  /** Подписана и содержимое меняется вместе с новой подписью: допустимо. */
  | 'переподписана'
  /** Подписана, содержимое меняется, новой подписи нет: недопустимо. */
  | 'нужна новая подпись';

/**
 * Можно ли заменить запись журнала новой.
 *
 * Сравнивается **подписанное содержимое**, а не запись целиком: служебные поля
 * — ссылка на версию регламента, время создания в хранилище — в подпись не
 * входят и смысла проверки не меняют. Иначе замена ломалась бы на пустом
 * месте, а человек не понимал бы, что именно ему не дают сделать.
 */
export function replacementVerdict(
  existing: MaintenanceEvent | null,
  next: MaintenanceEvent,
): ReplacementVerdict {
  if (existing === null) return 'новая запись';

  const signature = existing.signature ?? null;
  if (signature === null) return 'не подписана';

  const before = signedJournalContent(existing);
  const after = signedJournalContent(next);
  if (before === after) return 'содержимое то же';

  const fresh = next.signature ?? null;
  /*
   * Новой считается не всякая подпись, а поставленная под новым содержимым:
   * перенести прежнюю подпись в изменённую запись — тот же обман, только в
   * другом порядке действий.
   */
  if (fresh !== null && fresh.contentHash !== signature.contentHash) return 'переподписана';

  return 'нужна новая подпись';
}

/**
 * Записи журнала по объекту, заверенные простой электронной подписью.
 *
 * Нужно правке карточки. Подпись стоит под записью журнала, а не под карточкой,
 * но читают их вместе: в журнале печатается учётный номер и вид оборудования на
 * сегодня, а подписывали — то, что было в день проверки. Поменяли номер, и
 * подписанная строка стала говорить не то, под чем расписались.
 *
 * Простая электронная подпись сама неизменности не обеспечивает: она
 * подтверждает лишь, что подписал определённый человек (63-ФЗ, статья 5 часть
 * 2). Обеспечить неизменность подписанного обязана программа — иначе равенство
 * подписанного документа собственноручно подписанному (статья 9) держаться ни
 * на чём не будет.
 */
export function signedEventsOfObject(
  events: readonly MaintenanceEvent[],
  objectId: string,
): readonly MaintenanceEvent[] {
  return events.filter((event) => event.objectId === objectId && (event.signature ?? null) !== null);
}

/**
 * Что сказать человеку, прежде чем принять правку учётных данных.
 *
 * Не запрет, а честный выбор: правка нужна (номер и правда мог быть записан с
 * ошибкой), но подпись после неё держаться не может. Подпись снимается, и
 * запись подписывают заново — уже под новыми сведениями.
 */
export function signatureWithdrawalWarning(count: number): string {
  const записей = count === 1 ? 'запись' : 'записи';
  return `Правка учётных данных снимет простую электронную подпись: ею заверены `
    + `${записей} журнала — ${count}. Подпись подтверждает то, что было записано в день `
    + `проверки; после правки её придётся поставить заново. Продолжить?`;
}

/** Снять подпись с записи. Содержимое записи при этом не меняется. */
export function withoutSignature(event: MaintenanceEvent): MaintenanceEvent {
  return { ...event, signature: null };
}

/** Допустима ли замена. */
export function canReplaceEvent(
  existing: MaintenanceEvent | null,
  next: MaintenanceEvent,
): boolean {
  return replacementVerdict(existing, next) !== 'нужна новая подпись';
}

