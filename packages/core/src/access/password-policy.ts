/**
 * Требования к паролю и разбор попытки входа.
 *
 * Требования намеренно скромные: восемь знаков и не из списка очевидных.
 * Заставлять придумывать «Aa1!» на промышленном объекте — верный способ
 * получить пароль на стикере под клавиатурой. Длина важнее набора символов:
 * восемь знаков осмысленного пароля перебираются дольше, чем «Pa$$w0rd».
 *
 * Проверка входа возвращает причину отказа общей фразой. Разница между «нет
 * такого имени» и «неверный пароль» подсказывает подбирающему, какое имя
 * существует; человеку, который просто ошибся, эта разница ничего не даёт.
 */

import type { Result } from '@izh/contracts';
import { err, ok } from '@izh/contracts';

/** Короче этого пароль не принимается. */
export const MIN_PASSWORD_LENGTH = 8;

/**
 * Пароли, которые не принимаются, какой бы длины они ни были.
 *
 * Список короткий намеренно: он ловит не подбор, а бездумность — «12345678»
 * и «password» пробуют первыми всегда.
 */
const OBVIOUS_PASSWORDS: readonly string[] = [
  '12345678', '123456789', '1234567890', 'password', 'пароль', 'qwertyui',
  'йцукенг', '11111111', '00000000', 'admin123', 'администратор',
];

export function checkPasswordStrength(password: string): Result<void> {
  const value = password.trim();
  if (value.length < MIN_PASSWORD_LENGTH) {
    return err('INVALID_ARGUMENT', `Пароль короче ${MIN_PASSWORD_LENGTH} знаков.`);
  }
  if (OBVIOUS_PASSWORDS.includes(value.toLowerCase())) {
    return err('INVALID_ARGUMENT', 'Такой пароль подбирают первым. Придумайте другой.');
  }
  // Пароль из одного повторяющегося знака длину набирает, а стойкости не даёт.
  if (new Set(value).size < 4) {
    return err('INVALID_ARGUMENT', 'В пароле слишком мало разных знаков.');
  }
  return ok(undefined);
}

/** Общая фраза отказа: не подсказывает, что именно не подошло. */
export const SIGN_IN_REFUSED = 'Неверное имя или пароль.';
