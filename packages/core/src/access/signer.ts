/**
 * Кто подписывает и чем подтверждает, что это он.
 *
 * Одно описание на все места, где пароль спрашивается **один раз на действие**,
 * а подписей ставится много: перенос чужого журнала, заведение партии
 * оборудования, размещение очереди по щелчкам.
 *
 * Так просил заказчик: «при переносе журнала пользователь просто один раз
 * вводит пароль и подписывает ПЭП, а программа сама проставляет в каждую вновь
 * созданную строку ПЭП».
 *
 * Так и правильно. Подпись подтверждает, что подписал определённый человек
 * (63-ФЗ, статья 5 часть 2), а не то, что он нажал кнопку столько-то раз.
 * Человек один, действие одно — и требовать пароль на каждую из двухсот строк
 * значило бы превратить подпись в мучение и добиться того, что её станут
 * обходить.
 *
 * Отпечаток при этом у каждой подписанной записи свой: он берётся от её
 * собственного содержимого. Иначе одна подпись «на всё» не позволяла бы потом
 * сказать, какая именно строка изменилась после подписания.
 */

import type { PasswordHasher, SigningKeyService, UserAccount } from '@izh/contracts';

export interface Signer {
  readonly user: UserAccount;
  /** Пароль, введённый в момент подписания. В хранилище не попадает. */
  readonly password: string;
  readonly hasher: PasswordHasher;
  readonly keys?: SigningKeyService;
  /** Реквизиты документа организации о применении простой электронной подписи. */
  readonly basis?: string | null;
}
