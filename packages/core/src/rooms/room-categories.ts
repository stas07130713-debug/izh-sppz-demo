/**
 * Категории помещений по взрывопожарной и пожарной опасности.
 *
 * Перечень — по СП 12.13130: у помещений категории А, Б, В1–В4, Г, Д. Категория
 * не рассчитывается программой: для расчёта нужны перечень веществ, их
 * количество и теплота сгорания, которых в журнале СПЗ нет и не будет.
 * Пользователь выбирает значение из проекта или расчёта категорий и указывает
 * документ-основание.
 *
 * Цвет заливки на плане — условный, чтобы взрывопожароопасные помещения были
 * видны сразу. Он не является нормативным обозначением.
 */

export const ROOM_CATEGORIES: readonly string[] = [
  'А',
  'Б',
  'В1',
  'В2',
  'В3',
  'В4',
  'Г',
  'Д',
  'не категорируется',
];

/** Цвет заливки помещения на плане. Полупрозрачность задаётся при отрисовке. */
export function categoryColor(category: string | null): string {
  if (category === 'А') return '#dc2626';
  if (category === 'Б') return '#ea580c';
  if (category === 'В1' || category === 'В2') return '#d97706';
  if (category === 'В3' || category === 'В4') return '#ca8a04';
  if (category === 'Г') return '#2563eb';
  if (category === 'Д') return '#16a34a';
  return '#64748b';
}

/**
 * Требуется ли для этой категории повышенное внимание к первичным средствам.
 *
 * Пример из документов заказчика: огнетушители в помещениях категории А
 * проверяются не реже одного раза в 6 месяцев, а не раз в год. Сам срок задаётся
 * пакетом правил, здесь только признак — в коде нормативных сроков нет.
 */
export function isHighHazard(category: string | null): boolean {
  return category === 'А' || category === 'Б';
}
