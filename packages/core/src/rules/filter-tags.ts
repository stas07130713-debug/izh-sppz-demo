/**
 * Метки состояния для отбора (ТЗ, Дополнение 3, часть К3).
 *
 * Заказчик перечислил «В норме / Требует внимания / Просрочено / Неисправно /
 * Нет данных» одним плоским списком. В программе это две разные оси: срок
 * (`ScheduleStatus`) и исправность (`TechnicalState`). Разделять их в модели
 * правильно — просрочка и поломка разные вопросы, — а показывать надо вместе:
 * человек спрашивает «что не в порядке», а не «что не в порядке по срокам».
 *
 * Правило живёт в ядре, а не в разметке, потому что по нему считают трое:
 * нижняя полоса отбора, строки журнала и плитки дашборда. Пока оно стояло в
 * разметке, дашборд считал по-своему: «требует ремонта» попадало у него в
 * «Неисправно», а в журнале то же оборудование значилось «Требует внимания».
 * Плитка показывала единицу, журнал по нажатию — ноль.
 */

import { technicalEscalation, type ObjectCondition } from './object-condition.js';

export type FilterTag = 'норма' | 'скоро' | 'просрочено' | 'неисправно' | 'нет данных';

export const FILTER_TAG_ORDER: readonly FilterTag[] = [
  'норма', 'скоро', 'просрочено', 'неисправно', 'нет данных',
];

export const FILTER_TAG_LABELS: Readonly<Record<FilterTag, string>> = {
  'норма': 'В норме',
  'скоро': 'Требует внимания',
  'просрочено': 'Просрочено',
  'неисправно': 'Неисправно',
  'нет данных': 'Нет данных',
};

/**
 * Метки объекта: ровно один тег срока плюс, отдельно, поломка — если она есть.
 *
 * На вход идёт уже посчитанное состояние, а не объект: тем же значением
 * раскрашен значок на плане, и отбор не может разойтись с тем, что видно
 * глазами.
 *
 * «Неисправно» ставится только за настоящую поломку. «Исправен с замечаниями»,
 * «требует ремонта» и «на ТО» — это ещё не поломка, они дают «требует
 * внимания»: так же, как красит значок на плане.
 */
export function conditionFilterTags(condition: ObjectCondition): ReadonlySet<FilterTag> {
  const tags = new Set<FilterTag>([condition.schedule]);
  const alarm = technicalEscalation(condition.technical);
  if (alarm === 'danger') tags.add('неисправно');
  if (alarm === 'warn') tags.add('скоро');
  return tags;
}

/** Пустой выбор — отбор выключен, проходят все. Иначе — совпадение по «ИЛИ». */
export function matchesFilterTags(
  objectTags: ReadonlySet<FilterTag>,
  selected: ReadonlySet<FilterTag>,
): boolean {
  if (selected.size === 0) return true;
  for (const tag of objectTags) {
    if (selected.has(tag)) return true;
  }
  return false;
}
