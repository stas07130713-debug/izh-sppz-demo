/**
 * Обязательные требования нормативных правовых актов РФ.
 *
 * Отдельно от `rule-package.ts` намеренно. Там — типовые регламенты ГОСТ и СП:
 * организация вправе принять их, изменить или не применять вовсе. Здесь —
 * требования Правил противопожарного режима, утверждённых постановлением
 * Правительства РФ от 16.09.2020 № 1479. Их статус другой: отказ от них
 * оформляется решением организации и объясняется проверяющему, а не проходит
 * незаметной галочкой.
 *
 * Источник — справочник заказчика `ИЖ_СППЗ_периодичность_проверок_и_ТО_2026.docx`,
 * сводная таблица раздела 1, столбец «Статус требования» = «Обязательно».
 * Взято только то, что помечено обязательным там; ничего не додумано.
 *
 * Справочник сам предупреждает: «Перед вводом системы в эксплуатацию
 * нормативную базу следует повторно проверить на действующую редакцию».
 * Поэтому у записей стоит `needsVerification: true` — кроме тех, что сверены
 * отдельно и с датой сверки.
 *
 * Здесь остались только требования с **конкретным сроком**. Обновлено
 * 23.08.2026 по решению заказчика: общие обязанности «обслуживать по
 * регламенту» (ППР п. 54, абз. 1–3) и «вести учёт огнетушителей» (ППР п. 60)
 * из регламента убраны. Своего срока у них нет, и в чек-листе они давали
 * работу без даты — вечное «нет данных», от которого элемент выглядел
 * необслуженным. Сами обязанности при этом никуда не делись: их закрывают
 * конкретные работы — осмотр, ежегодная проверка, перезарядка, — и каждая уже
 * записывается в журнал эксплуатации.
 */

import type { ActivityRule } from './rule-package.js';
import { ELEMENT_FAMILIES } from '../objects/element-families.js';

/**
 * Ежегодные испытания оборудования, работающего сверх назначенного срока службы.
 *
 * Условное: применяется, только если срок службы изготовителя истёк либо
 * сведений о возможности дальнейшей эксплуатации нет. Пока это не так,
 * требование в чек-лист не идёт — потому `optIn`.
 */
export const PPR_ISPYTANIE_SVERH_SROKA: ActivityRule = {
  activityCode: 'ppr-ispytanie-sverh-sroka',
  title: 'Ежегодные испытания сверх срока службы',
  periodicityMonths: 12,
  checklist: [
    { text: 'Проведены испытания на работоспособность', severity: 'критический' },
    { text: 'Оформлен протокол испытаний', severity: 'значительный' },
    { text: 'Принято решение о дальнейшей эксплуатации или замене', severity: 'критический' },
  ],
  ndReference: 'ППР РФ №1479, п. 54, абз. 4 — при эксплуатации сверх срока службы изготовителя ежегодно до замены, обязательно',
  needsVerification: true,
  optIn: true,
};

/**
 * Средства противопожарной защиты, к которым относится требование ППР,
 * п. 54, абз. 4.
 *
 * Общие виды перечислены, исполнения добавляются сами из состава семейств.
 * Раньше перечень был плоским, и каждый новый вид оборудования — комбинированный
 * извещатель, речевой оповещатель, дымовой клапан — молча оставался без
 * обязательного требования: в каталоге он есть, в регламенте его нет.
 * Требование при этом обязательное, и потерять его тихо — худшее, что может
 * сделать программа.
 */
const SPZ_BASE_TYPES: readonly string[] = [
  'smoke-detector', 'heat-detector', 'flame-detector', 'fire-detector', 'manual-call-point',
  'control-panel', 'sounder', 'powder-module', 'gas-module', 'fire-suppression-system',
  'smoke-valve', 'smoke-fan', 'sprinkler', 'pump-station',
];

export const SPZ_SYSTEM_TYPES: readonly string[] = [...new Set([
  ...SPZ_BASE_TYPES,
  ...ELEMENT_FAMILIES
    .filter((family) => SPZ_BASE_TYPES.includes(family.parent))
    .flatMap((family) => family.members),
])];

/** Типы огнетушителей. Оставлены: по ним строится состав регламента огнетушителей. */
export const EXTINGUISHER_TYPES: readonly string[] = [
  'extinguisher', 'extinguisher-water', 'extinguisher-foam', 'extinguisher-emulsion',
  'extinguisher-powder', 'extinguisher-co2', 'extinguisher-halon', 'extinguisher-bantl',
];

/**
 * Обязательные требования НПА для типа оборудования.
 *
 * Возвращает пустой список, если для этого вида прямых требований ППР с
 * конкретным сроком нет. Это честный ответ, а не повод подставить
 * что-нибудь похожее: ошибка здесь оборачивается замечанием при проверке МЧС
 * у заказчика.
 */
export function npaRequirementsFor(typeCode: string): readonly ActivityRule[] {
  if (SPZ_SYSTEM_TYPES.includes(typeCode)) return [PPR_ISPYTANIE_SVERH_SROKA];
  return [];
}
