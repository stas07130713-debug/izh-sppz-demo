/**
 * Документы, которые человек обязан принять при первом входе.
 *
 * Заказчик: «пользователь при первом входе ОБЯЗАН прочитать и согласиться на
 * сбор и обработку персональных данных, а также с другими условиями работы в
 * программе».
 *
 * Принятие записывается **версией**, а не галочкой. Галочка отвечает на вопрос
 * «согласился ли», а нужен ответ на вопрос «с чем именно согласился»: текст
 * соглашения со временем меняется, и без версии через год нельзя ни показать
 * принятую редакцию, ни понять, требуется ли принять новую.
 *
 * Версия — дата редакции. Меняя тексты, обязательно меняют и её: иначе новая
 * редакция вступит в силу молча, а принятой будет считаться прежняя.
 */

import { AGREEMENT_TEXT, AGREEMENT_TITLE } from './agreement-text.js';
import { PRIVACY_TEXT, PRIVACY_TITLE } from './privacy-text.js';

/** Редакция документов. Дата в виде ГГГГ-ММ-ДД. */
export const LEGAL_VERSION = '2026-09-02';

export interface LegalDocument {
  readonly id: 'соглашение' | 'персональные данные';
  readonly title: string;
  readonly text: string;
  /**
   * Что человек подтверждает отметкой. Своя формулировка у каждого документа:
   * общая «согласен со всем» не годится — согласие на обработку персональных
   * данных даётся отдельно и осознанно (152-ФЗ, статья 9).
   */
  readonly consent: string;
}

export const LEGAL_DOCUMENTS: readonly LegalDocument[] = [
  {
    id: 'соглашение',
    title: AGREEMENT_TITLE,
    text: AGREEMENT_TEXT,
    consent: 'Я прочитал пользовательское соглашение и принимаю его условия',
  },
  {
    id: 'персональные данные',
    title: PRIVACY_TITLE,
    text: PRIVACY_TEXT,
    consent: 'Я даю согласие на обработку персональных данных на указанных условиях',
  },
];

/**
 * Нужно ли требовать принятия у этого человека.
 *
 * Требуется и тогда, когда принята прежняя редакция: изменённые условия — это
 * другие условия, и молча считать их принятыми нельзя.
 */
export function needsLegalAcceptance(acceptedVersion: string | null | undefined): boolean {
  return (acceptedVersion ?? null) !== LEGAL_VERSION;
}
