/**
 * Что можно поставить графой заявки (ТЗ, Дополнение 6, часть С54).
 *
 * Каталог, а не свободный ввод: заявка собирается из того, что программа уже
 * знает об оборудовании, и подставить она может только это. Своя графа —
 * отдельный, честно названный случай: она остаётся пустой и заполняется от
 * руки в готовом документе.
 */

export interface RequestColumnSource {
  readonly id: string;
  /** Название по умолчанию — его можно переписать своим. */
  readonly title: string;
  readonly hint: string;
}

/** Своё значение: программа его не подставляет, иначе оно было бы не своим. */
