export function dashboardBlock(id: string): DashboardBlock | null {
  return DASHBOARD_BLOCKS.find((block) => block.id === id) ?? null;
}

/**
 * Приводит сохранённый состав к рабочему виду.
 *
 * Незнакомые названия отбрасываются, повторы схлопываются. Настройки переживают
 * обновление программы: блок могли переименовать или убрать, и падать из-за
 * этого при открытии дашборда нельзя.
 */
export function normalizeDashboardBlocks(ids: readonly string[]): readonly string[] {
  // Нетронутый прежний состав заменяется новым: см. PREVIOUS_DEFAULT_SETS.
  if (PREVIOUS_DEFAULT_SETS.some((set) => sameBlocks(ids, set))) return RECOMMENDED_DASHBOARD_BLOCKS;

  const seen = new Set<string>();
  const result: string[] = [];
  for (const id of ids) {
    if (seen.has(id) || dashboardBlock(id) === null) continue;
    seen.add(id);
    result.push(id);
  }
  return result;
}

/** Тот же состав в том же порядке. */
function sameBlocks(a: readonly string[], b: readonly string[]): boolean {
  return a.length === b.length && a.every((id, index) => id === b[index]);
}
