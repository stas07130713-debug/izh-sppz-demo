/**
 * Свои названия встроенных видов оборудования.
 *
 * Заказчик: «в настройках во вкладке "элементы" добавь, чтобы можно было
 * заменять не только сами значки, но и название этих систем».
 *
 * И это то же самое требование, что и по значкам: на предприятии оборудование
 * зовут по-своему — «ПК» вместо «Пожарный кран», «ОП» вместо «Огнетушитель
 * порошковый», — и навязывать наши слова незачем. Название видно всюду:
 * в библиотеке, в журнале, на дашборде, в заявке и в печатных формах.
 *
 * Замена живёт здесь, а не в каждом месте показа, ровно по той же причине, что
 * и реестр своих видов: `elementByCode` вызывается из восьми десятков мест, и
 * подмешивать настройки в каждое значило бы переписать половину окна.
 *
 * Заменяется **только показываемое название**. Код вида, правила, справочники и
 * ссылки на нормативы остаются прежними: переименование — дело привычки
 * предприятия, а не смена сути оборудования.
 */

/** Пусто до первой загрузки настроек: у новой организации замен нет. */
let titles: Readonly<Record<string, string>> = {};

/**
 * Заменяет список целиком.
 *
 * Целиком, а не по одному: настройки приходят одним документом, и добавление по
 * одному оставило бы отменённое переименование в памяти до перезапуска.
 */
export function setElementTitleOverrides(next: Readonly<Record<string, string>>): void {
  titles = next;
}

/** Только для тестов: вернуть список в исходное состояние. */
export function resetElementTitleOverrides(): void {
  titles = {};
}

/** Все заведённые замены названий. */
export function elementTitleOverrides(): Readonly<Record<string, string>> {
  return titles;
}

/**
 * Своё название вида или `null`, если вид зовётся как в каталоге.
 *
 * Пустая строка и пробелы — это «названия нет», а не название: сохранённая по
 * ошибке пустая графа иначе стёрла бы название вида во всей программе.
 */
export function elementTitleOverride(typeCode: string): string | null {
  const value = titles[typeCode];
  if (value === undefined) return null;
  const trimmed = value.trim();
  return trimmed === '' ? null : trimmed;
}
