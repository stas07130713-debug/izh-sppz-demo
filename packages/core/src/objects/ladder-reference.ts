/**
 * Справочник наружной пожарной лестницы (ГОСТ Р 53254-2009).
 *
 * Тип определяет и устройство лестницы, и объём её испытаний: у вертикальной
 * проверяют ступени и крепление к стене, у маршевой — ещё марши, площадки и
 * перила. Поэтому тип не украшение карточки, а признак, от которого зависит,
 * что именно будут проверять.
 *
 * Подтип привязан к типу: у вертикальной он говорит, нужно ли ограждение
 * (с высоты 6 м оно обязательно), у маршевой подтип один.
 */

/** Типы по ГОСТ Р 53254-2009, п. 4.1. */
export const LADDER_TYPES: readonly string[] = [
  'П1 — вертикальная',
  'П2 — маршевая',
];

/**
 * Подтипы по типу лестницы.
 *
 * Списком по типу, а не одним общим: подтип П2 у вертикальной лестницы
 * бессмыслен, и предлагать его значило бы приглашать к ошибке.
 */
export const LADDER_SUBTYPES: Readonly<Record<string, readonly string[]>> = {
  'П1 — вертикальная': [
    'П1-1 — без ограждения, высотой до 6 м',
    'П1-2 — с ограждением, высотой более 6 м',
  ],
  'П2 — маршевая': ['П2 — с маршами, площадками и перилами'],
};

/** Подтипы выбранного типа. Пустой список — тип не выбран. */
export function ladderSubtypesFor(ladderType: string | null): readonly string[] {
  return ladderType === null ? [] : LADDER_SUBTYPES[ladderType] ?? [];
}

/** Где лестница стоит. Список-подсказка: своё место вводится в том же поле. */
export const LADDER_PLACES: readonly string[] = [
  'главный фасад',
  'дворовый фасад',
  'торец здания',
  'перепад высот кровли',
  'выход на кровлю',
  'пристройка',
];

/** Ограждение и площадка отвечаются прямо: «нет» — это ответ, а не пустое поле. */
export const LADDER_PRESENCE: readonly string[] = ['есть', 'нет'];
