/**
 * Требуемая высота ограждения кровли по высоте здания
 * (ГОСТ Р 53254-2009, таблица 3).
 *
 * Нужна, чтобы карточка могла сказать: ограждение цело, но ниже положенного.
 * Одной лишь целостности мало — низкое ограждение не удержит человека.
 */
const FENCE_HEIGHT_BY_BUILDING: readonly { readonly upToM: number; readonly requiredM: number }[] = [
  { upToM: 20, requiredM: 0.6 },
  { upToM: 30, requiredM: 0.8 },
  { upToM: 50, requiredM: 1.0 },
  { upToM: Number.POSITIVE_INFINITY, requiredM: 1.1 },
];

/** Какой высоты должно быть ограждение при такой высоте здания. */
export function requiredFenceHeight(buildingHeightM: number | null): number | null {
  if (buildingHeightM === null || buildingHeightM <= 0) return null;
  return FENCE_HEIGHT_BY_BUILDING.find((row) => buildingHeightM <= row.upToM)?.requiredM ?? null;
}

