/**
 * Кто отвечает за оборудование (ТЗ, Дополнение 6).
 *
 * Раньше ответственного вписывали в каждую карточку руками. При сотне
 * огнетушителей это сотня одинаковых строк, и при смене человека их пришлось бы
 * править по одной — а какую-нибудь всё равно пропустили бы, и в журнале
 * осталась бы фамилия уволившегося.
 *
 * Поэтому ответственный не хранится у объекта, а берётся сверху: с ближайшего
 * узла дерева, где он назначен. Обычно это здание — в его профиле есть поле
 * «Ответственный за пожарную безопасность».
 *
 * Когда появятся роли и учётные записи, источником станет запись о назначении
 * человека ответственным на этом объекте. Меняться будет только эта функция:
 * все карточки и журнал спрашивают ответственного здесь.
 */

import type { PlanObject, TreeNode } from '@izh/contracts';
import { pathToNode } from '../object-tree/tree-shape.js';

/**
 * Ответственный за объект: ближайший назначенный вверх по дереву.
 *
 * `null` — не назначен нигде. Это честный ответ, а не повод подставить пустую
 * строку: пустая графа в журнале означает «не назначен», и её видно.
 *
 * Собственное поле объекта учитывается первым — в старых данных оно заполнено,
 * и молча его игнорировать значило бы потерять сведения, которые пользователь
 * уже внёс.
 */
export function responsibleFor(
  nodes: readonly TreeNode[],
  object: PlanObject,
): string | null {
  const own = clean(object.responsible);
  if (own !== null) return own;

  // От объекта вверх: этаж, здание, цех, организация. Берётся ближайший — он
  // и отвечает за это оборудование.
  const path = [...pathToNode(nodes, object.nodeId)].reverse();
  for (const node of path) {
    const assigned = clean(node.building?.responsible ?? null);
    if (assigned !== null) return assigned;
  }
  return null;
}

function clean(value: string | null | undefined): string | null {
  if (value === null || value === undefined) return null;
  const trimmed = value.trim();
  return trimmed === '' ? null : trimmed;
}
