/** Значение, которым пользователь говорит «в списке этого нет». */
export const OTHER_CONTROL_PANEL = 'другое';

/** Модели изготовителя по виду оборудования. Пустой список — марка вводится текстом. */
export function automationModels(manufacturer: string, typeCode: string): readonly string[] {
  return AUTOMATION_MANUFACTURERS.find((item) => item.name === manufacturer)?.models[typeCode] ?? [];
}

/** Есть ли такой изготовитель в справочнике. Введённого вручную здесь нет — и это нормально. */
export function isKnownAutomationManufacturer(manufacturer: string | null): boolean {
  return manufacturer !== null && AUTOMATION_MANUFACTURERS.some((item) => item.name === manufacturer);
}

