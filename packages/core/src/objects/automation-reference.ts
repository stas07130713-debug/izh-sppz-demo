/**
 * Справочник оборудования пожарной автоматики (ТЗ, Дополнение 6).
 *
 * Нужен, чтобы марку не набирали руками. Один и тот же прибор пишут как
 * «С2000М», «с2000 м» и «Болид С2000М» — и в журнале это оказывается три
 * разных прибора, которые не сходятся ни в фильтре, ни в выгрузке.
 *
 * Устроен от изготовителя: сначала он, потом его модели по виду оборудования.
 * Так и подбирают на объекте — извещатель берут того же изготовителя, что и
 * прибор, иначе он с ним попросту не заработает: протокол адресной линии у
 * каждого свой.
 *
 * Список — подсказка, а не ограничение: рядом всегда есть «Другой
 * изготовитель» и «Другая модель», и введённое вручную сохраняется как есть.
 * Дополнять его можно свободно — от состава списка не зависит ни одна проверка
 * и ни один срок.
 *
 * Состав сверен 24.08.2026 по каталогам изготовителей: bolid.ru,
 * products.rubezh.ru, catalog.argus-spectr.ru. Взяты линейки, которые
 * встречаются на объектах чаще прочих; полного перечня выпускаемого
 * оборудования здесь нет и быть не должно. У изготовителей, чьи модели не
 * сверены, список пуст — марка вводится текстом. Это честнее выдуманного
 * перечня: ошибка в марке уходит в журнал и предъявляется проверяющему.
 */

