/**
 * Чего не хватает в карточке элемента.
 *
 * Заказчик о колокольчике: «информация по блокам из ТО + те, что требуют
 * заполнения и размещения».
 *
 * «Требуют заполнения» — это карточки, по которым нельзя ни отчитаться, ни
 * предъявить оборудование: без учётного номера единицу не найти в журнале, без
 * даты ввода в эксплуатацию не посчитать ни один срок, без ответственного
 * непонятно, с кого спрашивать.
 *
 * Набор нарочно короткий и одинаковый для всех видов. Полный список
 * обязательных полей у огнетушителя длиннее — он проверяется в самой карточке,
 * при сохранении. Здесь другой вопрос: не «всё ли заполнено идеально», а «можно
 * ли этой записью пользоваться вообще». Строгий список превратил бы счётчик в
 * «требуют заполнения: 124» — число, на которое перестают смотреть.
 */

import type { PlanObject } from '@izh/contracts';

/** Чего не хватает. Пустой список — карточкой можно пользоваться. */
export function missingCardFields(object: PlanObject): readonly string[] {
  const missing: string[] = [];

  if ((object.regNumber ?? '').trim() === '') missing.push('учётный номер');
  if ((object.commissionedOn ?? '').trim() === '') missing.push('дата ввода в эксплуатацию');
  if ((object.responsible ?? '').trim() === '') missing.push('ответственный');

  return missing;
}

/**
 * Карточки, которые требуют заполнения.
 *
 * Выведенные из эксплуатации не считаются: их не обслуживают, и дозаполнять
 * там нечего — запись хранится ради истории.
 */
export function incompleteCards(objects: readonly PlanObject[]): readonly PlanObject[] {
  return objects.filter((object) => object.archivedAt === null && missingCardFields(object).length > 0);
}
