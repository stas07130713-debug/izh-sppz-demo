/**
 * Пустой бланк раздела — не данные (ТЗ, часть С103).
 *
 * Заказчик: «при загрузке журнала не определяет пустые незаполненные строки и
 * предлагает выбрать этот раздел».
 */

import { describe, expect, it } from 'vitest';
import { filledRowCount, isFilledRow } from '../import/filled-rows.js';

describe('строка с данными', () => {
  it('совсем пустая строка — не данные', () => {
    expect(isFilledRow(['', '   ', ''])).toBe(false);
  });

  it('одна только нумерация — не данные', () => {
    // Тот самый случай: бланк раздела приходит с проставленными 1, 2, 3…
    expect(isFilledRow(['1', '', '', ''])).toBe(false);
    expect(isFilledRow(['', '12.', '', ''])).toBe(false);
  });

  it('одно слово — уже сведение', () => {
    expect(isFilledRow(['', 'ОП-4', '', ''])).toBe(true);
  });

  it('две заполненные ячейки — данные при любом содержании', () => {
    expect(isFilledRow(['1', '45931', '', ''])).toBe(true);
  });
});

describe('счёт строк листа', () => {
  const header = ['№', 'Наименование', 'Дата'];

  it('бланк с нумерацией считается пустым', () => {
    const rows = [header, ['1', '', ''], ['2', '', ''], ['3', '', '']];
    expect(filledRowCount(rows, 0)).toBe(0);
  });

  it('заполненные строки считаются', () => {
    const rows = [header, ['1', 'ОП-4 № 12', '01.03.2026'], ['2', '', ''], ['3', 'ОП-4 № 13', '01.03.2026']];
    expect(filledRowCount(rows, 0)).toBe(2);
  });

  it('без строки заголовков считать нечего', () => {
    expect(filledRowCount([['что-то', 'ещё']], null)).toBe(0);
  });

  it('строки выше заголовков не в счёт: там шапка журнала', () => {
    const rows = [['Журнал учёта'], ['АО «Кольская ГМК»'], header, ['1', 'ОП-4 № 12', '01.03.2026']];
    expect(filledRowCount(rows, 2)).toBe(1);
  });
});
