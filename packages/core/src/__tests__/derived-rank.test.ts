/**
 * Ранг, вычисленный по марке и заряду (ТЗ, Дополнение 6, часть С88).
 *
 * Заказчик: «ранги пожаров на огнетушителе должны вычисляться самостоятельно
 * программой в зависимости от вида заведённого в программу огнетушителя, по его
 * характеристикам».
 *
 * Ранг не выдумывается: он читается из таблицы 3 в обратную сторону. «≥ ОП-6» в
 * строке класса A означает, что ОП-6 обеспечивает 3A — значит, по ОП-6 можно
 * вернуть 3A, не спрашивая человека.
 *
 * Это нижняя оценка, и проверки закрепляют именно её границы: где таблица
 * молчит, ранг не досочиняется.
 */

import { describe, expect, it } from 'vitest';
import { derivedRank, formatFireRank } from '../index.js';

const shown = (mark: string, charge: number): string => {
  const rank = derivedRank(mark, charge);
  return rank === null ? '' : formatFireRank(rank);
};

describe('ранг по марке и заряду', () => {
  it('порошковый шестикилограммовый — 3A, 70B, C, E', () => {
    // Верхняя строка таблицы 3: A при ОП ≥ 6, B при ОП ≥ 6, C при ОП ≥ 6,
    // E при ОП ≥ 4. Все требования закрыты.
    expect(shown('ОП', 6)).toBe('3A, 70B, C, E');
  });

  it('порошковый четырёхкилограммовый — на строку ниже: 2A, 55B, C, E', () => {
    // Для верхней строки заряда не хватает, для нижней хватает.
    expect(shown('ОП', 4)).toBe('2A, 55B, C, E');
  });

  it('углекислотный не тушит класс A — и ранг это показывает', () => {
    // В таблице 3 марки ОУ нет ни в одной строке класса A.
    expect(shown('ОУ', 5)).toBe('55B, C, E');
  });

  it('заряд ниже наименьшего по таблице не даёт ничего', () => {
    // ОП-2: ни одна строка не выполняется, ранг не вычисляется.
    expect(derivedRank('ОП', 2)).toBeNull();
  });

  it('больший заряд не понижает ранг', () => {
    const six = derivedRank('ОП', 6);
    const twelve = derivedRank('ОП', 12);
    expect(twelve?.a ?? 0).toBeGreaterThanOrEqual(six?.a ?? 0);
    expect(twelve?.b ?? 0).toBeGreaterThanOrEqual(six?.b ?? 0);
  });

  it('без марки или без заряда ранг не выдумывается', () => {
    expect(derivedRank(null, 8)).toBeNull();
    expect(derivedRank('ОП', null)).toBeNull();
  });

  it('воздушно-эмульсионный: таблица даёт A и B, про C и E молчит', () => {
    // Молчание таблицы — не отрицание: класс E у ОВЭ подтверждают испытаниями,
    // и вписанный в карточку ранг такое молчание перекрывает.
    expect(shown('ОВЭ', 10)).toBe('3A, 70B');
  });
});
