/**
 * Что о заряде огнетушителя уже сказано другими полями карточки.
 *
 * Заказчик: «нужно в карточке огнетушителя несколько раз вводить одни и те же
 * данные, чтобы определился ранг. Программа должна определять ранг из
 * информации, которая уже введена, — о виде ОТВ и объёме огнетушителя».
 *
 * И он прав: к тому времени, когда человек доходит до полей «огнетушащее
 * вещество» и «заряд», он уже дважды это сказал —
 *
 *   видом изделия:  «Огнетушитель порошковый»  →  вещество порошок;
 *   моделью:        «ОП-4»                     →  четыре килограмма.
 *
 * Здесь это и вычитывается. Вычитанное подставляется в карточку как обычное
 * значение, а не как отдельная «умная» ветка расчёта: ранг, проверка
 * расстановки, журнал и печатные формы продолжают читать те же поля профиля, и
 * второго пути вычисления, который однажды разойдётся с первым, не появляется.
 *
 * Подстановка не запрет: вписанное человеком главнее. Огнетушитель бывает
 * перезаряжен другим составом, а модель — набрана своя, не из справочника.
 */

import type { ExtinguisherAgent, ExtinguisherProfile } from '@izh/contracts';

/**
 * Огнетушащее вещество, вытекающее из вида изделия.
 *
 * Общий вид «Огнетушитель» сюда не входит намеренно: он и заведён для случая,
 * когда вид ещё не уточнён, и придумывать за человека вещество нельзя.
 */
const AGENT_BY_TYPE: ReadonlyMap<string, ExtinguisherAgent> = new Map([
  ['extinguisher-powder', 'порошок'],
  ['extinguisher-co2', 'углекислота'],
  ['extinguisher-halon', 'хладон'],
  ['extinguisher-water', 'вода'],
  ['extinguisher-foam', 'пена'],
  // Воздушно-эмульсионный тушит водой с добавками: в таблице 3 он идёт как
  // ОВЭ, и заряд у него меряется литрами, а не килограммами.
  ['extinguisher-emulsion', 'вода с добавками'],
  ['extinguisher-bantl', 'вода с добавками'],
]);

export function agentOfType(typeCode: string): ExtinguisherAgent | null {
  return AGENT_BY_TYPE.get(typeCode) ?? null;
}

/**
 * Огнетушащее вещество, названное самим обозначением модели.
 *
 * По ГОСТ Р 51057 обозначение начинается с букв вида: ОП — порошковый, ОУ —
 * углекислотный, ОВП — воздушно-пенный, ОВЭ — воздушно-эмульсионный, ОВ —
 * водный, ОХ — хладоновый. То есть человек, написавший «ОП-5», уже сказал, что
 * это порошок, — спрашивать вещество отдельно значит просить повторить.
 *
 * Нужно это чаще, чем кажется. Вид «Огнетушитель» без уточнения подвида — то,
 * что программа ставит сама при переносе журнала и при укладке значка на план,
 * и до этой правки такая карточка не давала ни вещества, ни ранга: подвид не
 * выбран, а обозначение никто не читал.
 *
 * Длинные буквосочетания проверяются раньше коротких: «ОВП» и «ОВЭ» начинаются
 * с «ОВ», и общее правило забрало бы их себе.
 */
const AGENT_BY_DESIGNATION: readonly (readonly [string, ExtinguisherAgent])[] = [
  ['овп', 'пена'],
  ['овэ', 'вода с добавками'],
  ['оп', 'порошок'],
  ['оу', 'углекислота'],
  ['ох', 'хладон'],
  ['ов', 'вода'],
];

export function agentFromModel(model: string | null | undefined): ExtinguisherAgent | null {
  if (model === null || model === undefined) return null;
  const text = model.trim().toLocaleLowerCase('ru');
  for (const [designation, agent] of AGENT_BY_DESIGNATION) {
    // Только начало обозначения и только перед разделителем: «Буран-8» не
    // должен читаться как что-либо, а «ОП-5 Ярпожинвест» — читаться должен.
    if (new RegExp(`^${designation}\\s*[-–(\\d]`, 'u').test(text)) return agent;
  }
  return null;
}

/**
 * Заряд, записанный в самом обозначении модели: «ОП-4» — четыре килограмма.
 *
 * Обозначение читается по правилу ГОСТ Р 51057: буквы вида, дефис, число
 * заряда, дальше в скобках способ вытеснения и классы — «ОП-4(з) ABCE». Всё,
 * что после числа, к заряду отношения не имеет.
 *
 * Число ищется только сразу за буквами вида. Иначе «ОП-4(з) ABCE 2A 55B»
 * дало бы 55: в обозначении хватает других чисел, и взять первое попавшееся
 * значило бы иногда молча подставить в карточку чужую величину.
 */
export function chargeFromModel(model: string | null | undefined): number | null {
  if (model === null || model === undefined) return null;

  const match = /^\s*(?:ОП|ОУ|ОВП|ОВЭ|ОВ|ОХ)\s*\(?[^\d-]*\)?\s*-\s*(\d+(?:[.,]\d+)?)/iu.exec(model);
  if (match === null) return null;

  const value = Number((match[1] as string).replace(',', '.'));
  return Number.isFinite(value) && value > 0 ? value : null;
}

export interface ImpliedProfileInput {
  readonly typeCode: string;
  readonly model: string | null;
  readonly profile: ExtinguisherProfile | null;
}

/**
 * Чего в профиле недостаёт, но что уже известно из вида и модели.
 *
 * Возвращает только недостающее — пустой объект означает «дополнять нечего».
 * Так вызывающему коду не приходится сравнивать поля вручную, а уже
 * заполненное человеком не перетирается.
 */
export function impliedProfileFields(input: ImpliedProfileInput): Partial<ExtinguisherProfile> {
  // Собирается изменяемым объектом и отдаётся неизменяемым: поля профиля
  // только для чтения, и дописывать их в готовый профиль нельзя.
  const filled: { agent?: ExtinguisherAgent; nominalCharge?: number } = {};

  if ((input.profile?.agent ?? null) === null) {
    // Сначала вид изделия, потом обозначение модели: вид выбирают руками, а
    // обозначение бывает набрано с опечаткой или своё, не из справочника.
    const agent = agentOfType(input.typeCode) ?? agentFromModel(input.model);
    if (agent !== null) filled.agent = agent;
  }

  if ((input.profile?.nominalCharge ?? null) === null) {
    const charge = chargeFromModel(input.model);
    if (charge !== null) filled.nominalCharge = charge;
  }

  return filled;
}
