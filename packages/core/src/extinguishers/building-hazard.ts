/**
 * Сведения объекта защиты для расчёта огнетушителей.
 *
 * Заказчик: «для расчёта проверки огнетушителей не нужно категорирование всех
 * помещений, достаточно категорию и функциональное назначение самого здания».
 *
 * Это верно и по существу. Обводить и категорировать каждое помещение — работа
 * на недели, а ППР задаёт норму по категории, назначению и площади; всё это в
 * характеристике здания уже есть. Помещения остаются уточнением: там, где они
 * заведены и обведены, проверка идёт по ним и умеет считать расстояния по
 * плану. Там, где их нет, считается по зданию целиком.
 *
 * Назначение отдельным полем не спрашивается: его даёт
 * `purposeOfFunctionalClasses` по классу функциональной пожарной опасности —
 * Ф5.1 это и есть «производственное», и повторять уже написанное незачем.
 */

import type { RoomPurpose } from './ppr-tables.js';

/**
 * Что известно об объекте защиты целиком.
 *
 * Те же четыре сведения, что и у помещения: категория, назначение, площадь и
 * классы возможного пожара. По ним считается и норма помещения — разница только
 * в том, откуда они взяты.
 */
export interface BuildingHazard {
  readonly category: string | null;
  readonly purpose: RoomPurpose | null;
  readonly areaM2: number | null;
  readonly fireClasses: readonly string[];
  readonly hasSuppression: boolean;
}
