/**
 * Типовые помещения и то, что из них следует для норм по огнетушителям.
 *
 * Заказчик: «сделай выпадающий список в карточке узла, чтобы там были варианты
 * помещений, для которых есть отдельные требования по размещению
 * огнетушителей».
 *
 * Отдельные требования ППР (пункт 409, приложения № 1 и 2) держатся на трёх
 * сведениях о помещении: **категория**, **назначение** и **классы возможного
 * пожара**. Категорию программа не назначает и назначать не вправе — она
 * выводится расчётом по СП 12.13130 и утверждается организацией. А назначение
 * и классы пожара следуют из того, что в помещении находится и горит, и вот их
 * список ниже и подставляет.
 *
 * Это **подсказка, а не норма**: значения встают в поля карточки, где их видно
 * и где их можно поправить. Программа не решает за человека, а избавляет его от
 * необходимости помнить, что в электрощитовой горит класс E, а в архиве — A.
 *
 * Классы даны по ГОСТ 27331: A — твёрдые горючие, B — горючие жидкости,
 * C — горючие газы, D — металлы, E — электроустановки под напряжением.
 */

import type { FireClass } from './fire-rank.js';
import type { RoomPurpose } from './ppr-tables.js';

export interface RoomKind {
  readonly id: string;
  readonly title: string;
  /** Назначение по ППР: от него зависит расстояние до огнетушителя. */
  readonly purpose: RoomPurpose;
  /** Классы возможного пожара — по тому, что в помещении горит. */
  readonly fireClasses: readonly FireClass[];
  /** Почему именно так. Показывается рядом с выбором — норму видно, а не угадывают. */
  readonly why: string;
}

