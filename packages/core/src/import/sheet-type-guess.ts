/**
 * Подсказка по названию раздела. `null` — ничего похожего, выбирает человек.
 *
 * Молчание здесь честнее догадки: неверно подставленный вид уводит весь раздел
 * журнала не туда, и заметить это можно уже после переноса.
 */
export function guessTypeFromSheetName(sheetName: string): SheetTypeGuess | null {
  const clean = sheetName.toLocaleLowerCase('ru').replace(/ё/g, 'ё').trim();
  const name = ` ${clean} `;

  for (const [word, typeCode] of BY_WORD) {
    if (name.includes(word)) return { typeCode, matched: word.trim() };
  }

  /*
   * Обрезанное название листа.
   *
   * Excel не хранит имена длиннее 31 знака и молча режет: раздел «Внутренний
   * противопожарный водопровод» приходит как «Внутренний противопожарный
   * водо». Целого слова в нём уже нет, и поиск по вхождению давал «похожего
   * раздела не нашлось» — на самом частом названии раздела из настоящих
   * журналов.
   *
   * Поэтому вторым заходом проверяется обратное: не начинается ли **признак** с
   * названия листа. Двенадцать знаков — порог, ниже которого совпадение
   * начала уже ничего не значит: «пожарн» подошло бы к пяти разным разделам.
   */
  if (clean.length >= 12) {
    for (const [word, typeCode] of BY_WORD) {
      if (word.startsWith(clean)) return { typeCode, matched: word.trim() };
    }
  }

  return null;
}
