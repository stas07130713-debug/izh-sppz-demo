/**
 * Какой раздел переносимого журнала какому виду оборудования отвечает.
 *
 * Заказчик: «программа должна в графу сама подставлять схожий раздел —
 * например, там огнетушители и у нас соответственно огнетушители, но чтобы
 * решение оставалось за пользователем».
 *
 * Поэтому здесь именно **подсказка**, а не сопоставление: названия разделов в
 * журналах предприятий свои у каждого, и ошибиться легко. Программа называет
 * подходящий вид и говорит, по какому слову решила; выбор остаётся за
 * человеком, и переключить его можно всегда.
 *
 * Слова лежат таблицей, а не набором `if`: перечень разделов у заказчиков
 * пополняется, и дописывать строку в таблицу должно быть проще, чем читать
 * код (AGENTS.md, правило 9).
 */

export interface SheetTypeGuess {
  readonly typeCode: string;
  /** По какому слову решено — показывается человеку рядом с подсказкой. */
  readonly matched: string;
}

