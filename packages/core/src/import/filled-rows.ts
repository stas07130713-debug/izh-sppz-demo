/**
 * Есть ли в листе переносимого журнала настоящие данные.
 *
 * Заказчик: «при загрузке журнала не определяет пустые незаполненные строки и
 * предлагает выбрать этот раздел, так быть не должно».
 *
 * Прежде строка считалась данными, если хоть одна её ячейка не пуста. В книгах
 * учёта это почти всегда правда — и почти всегда неверно: типовой бланк
 * раздела приходит с заранее проставленной нумерацией 1, 2, 3… и пустыми
 * остальными графами. Формально не пуст, по существу — чистый бланк.
 *
 * Правило здесь другое: строка считается заполненной, если в ней есть хоть
 * что-то, кроме порядкового номера. Одна ячейка с числом — это нумерация;
 * одна ячейка со словом — это уже сведение (учётный номер, место, примечание);
 * две и более заполненных ячейки — данные при любом их содержании.
 */

/** Похоже ли значение на порядковый номер строки бланка: «1», «12», «3.». */
function looksLikeOrdinal(value: string): boolean {
  return /^\d{1,4}[.)]?$/.test(value.trim());
}

/**
 * Заполнена ли строка по существу.
 *
 * Экспортируется отдельно: по этому же правилу разбор пропускает хвост бланка,
 * и два разных ответа на вопрос «есть ли здесь данные» разошлись бы.
 */
export function isFilledRow(row: readonly string[]): boolean {
  const filled = row.filter((cell) => cell.trim() !== '');
  if (filled.length === 0) return false;
  if (filled.length >= 2) return true;
  return !looksLikeOrdinal(filled[0] as string);
}

/**
 * Сколько строк с данными ниже строки заголовков.
 *
 * `headerRow === null` — заголовков нет, значит это и не таблица учёта: считать
 * нечего.
 */
export function filledRowCount(rows: readonly (readonly string[])[], headerRow: number | null): number {
  if (headerRow === null) return 0;
  return rows.slice(headerRow + 1).filter(isFilledRow).length;
}
