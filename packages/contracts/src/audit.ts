/**
 * Журнал действий пользователей.
 *
 * Заказчик: «сделай ещё одну вкладку, куда будет вноситься история по действиям
 * в программе пользователей — кратко: когда заходил, что сделал, кого создали,
 * удалили и тому подобное. Чтобы не много места занимала эта база данных,
 * записывать события за последние 30 дней. Доступно к просмотру только
 * администратору».
 *
 * Чем он отличается от двух других журналов программы:
 *
 *  - **журнал эксплуатации** (maintenance) — про оборудование: какие проверки
 *    проведены. Он не удаляется никогда, его предъявляют при проверке;
 *  - **журнал изменений** (change-log) — про данные: какое поле у какой карточки
 *    поменялось;
 *  - этот — про **людей**: кто вошёл, кто кого завёл, отключил, удалил, кто
 *    подписал запись. Он служебный, живёт тридцать дней и стареет сам.
 *
 * Тридцать дней — прямое требование заказчика, и оно разумно: журнал действий
 * отвечает на вопрос «что происходило на днях», а не «что было год назад».
 * Всё, что должно храниться дольше, хранится в двух других журналах.
 */

import type { IsoDateTime } from './basic-types.js';
import type { UserId, UserRole } from './access.js';
import type { Result } from './result.js';

/** Что произошло. Список закрытый: журнал должен читаться, а не разрастаться. */
export type AuditKind =
  | 'вход'
  | 'выход'
  | 'отказ во входе'
  | 'заведён пользователь'
  | 'изменён пользователь'
  | 'отключён пользователь'
  | 'включён пользователь'
  | 'удалён пользователь'
  | 'сброшен пароль'
  | 'изменён пароль'
  | 'подписана запись'
  | 'выгружен журнал'
  | 'изменены настройки';

export interface AuditEvent {
  readonly id: string;
  readonly at: IsoDateTime;
  /**
   * Кто действовал. Снимок, а не ссылка: человек меняет должность и уходит, а
   * запись должна и через месяц говорить, кем он был тогда.
   */
  readonly actorId: UserId | null;
  readonly actorName: string;
  readonly actorRole: UserRole | null;
  readonly kind: AuditKind;
  /**
   * Над кем или над чем действовали: «Петров П. П.», «Огнетушитель № 12».
   * Пусто — действие само по себе, как вход в программу.
   */
  readonly subject: string | null;
  /** Короткое пояснение, если оно что-то добавляет: «роль: гость». */
  readonly details: string | null;
}

/**
 * Хранение журнала действий.
 *
 * Удаление здесь есть — и это единственный журнал программы, где оно есть.
 * Правило «историю не удаляем» относится к журналу эксплуатации: он
 * доказательство проведённых работ. Журнал действий — служебный след, и
 * заказчик прямо просил ограничить его тридцатью днями.
 */
export interface AuditRepository {
  list(): Promise<Result<readonly AuditEvent[]>>;
  append(event: AuditEvent): Promise<Result<void>>;
  /** Убирает всё, что старше указанного дня. Возвращает число убранных. */
  prune(olderThan: IsoDateTime): Promise<Result<number>>;
}
