/**
 * Свой вид противопожарного элемента (движок E4, конструктор типов).
 *
 * Каталог видов в ядре покрывает то, что встречается на большинстве
 * предприятий, но не может покрыть всё: у одного завода своя система
 * пенотушения, у другого — учёт кошм и ящиков с песком по своей форме. Чтобы
 * такой элемент завести, программиста быть не должно.
 *
 * Свой вид описывается тем же, чем встроенный: значок на плане (картинкой или
 * буквенной пометкой), название, где применяется и какие поля в карточке.
 *
 * Чек-лист и периодичность в этом типе не лежат намеренно, хотя задаются в том
 * же окне конструктора: они хранятся регламентом (Дополнение 5, область «тип
 * оборудования»), как у встроенных видов. Иначе у сроков было бы два места
 * хранения, и они разошлись бы на первой же правке.
 */

import type { IsoDateTime } from './basic-types.js';

/**
 * Где применяется свой вид.
 *
 * Названо по-русски и по смыслу для пользователя, а не кодами рабочих
 * областей: контракты не знают о `PlanKind` — это правило ядра, — а человек в
 * настройках выбирает не «floor», а «поэтажный план».
 */
export type CustomElementPlacement = 'генплан' | 'этаж' | 'склад';

export const CUSTOM_ELEMENT_PLACEMENTS: readonly CustomElementPlacement[] = ['генплан', 'этаж', 'склад'];

/**
 * Из чего собирается поле карточки.
 *
 * Палитра закрытая и намеренно короткая. Свободная форма (ввод любых типов,
 * формул, вычисляемых полей) превратила бы настройки в язык программирования,
 * а карточку — в то, что нельзя ни проверить, ни выгрузить в отчёт.
 */
export type CustomFieldKind = 'текст' | 'число' | 'дата' | 'список' | 'да/нет';

export const CUSTOM_FIELD_KINDS: readonly CustomFieldKind[] = ['текст', 'число', 'дата', 'список', 'да/нет'];

export interface CustomField {
  /** Неизменный ключ поля. К нему привязаны значения в карточках элементов. */
  readonly id: string;
  readonly title: string;
  readonly kind: CustomFieldKind;
  /** Варианты для вида «список». У остальных пустой. */
  readonly options: readonly string[];
  /** Единица измерения для вида «число»: кг, м, шт. */
  readonly unit: string | null;
  /** Подсказка под полем: чем оно заполняется и откуда берётся. */
  readonly hint: string | null;
}

export interface CustomElementType {
  /**
   * Внутренний код вида. Начинается с `custom-`, чтобы ни при каких
   * обстоятельствах не совпасть с кодом встроенного вида: коды встроенных
   * закреплены правилами и справочниками, и столкновение подменило бы вид
   * оборудования у уже заведённых объектов.
   */
  readonly typeCode: string;
  readonly title: string;
  /** Короткая пометка на значке плана: длинное название туда не помещается. */
  readonly mark: string;
  /** Цвет значка на плане. */
  readonly color: string;
  /**
   * Картинка значка: `data:image/png;base64,…` или пусто.
   *
   * Заказчик: «чтобы можно было назначить картинкой значок». Хранится
   * прямо в настройках, а не файлом в хранилище: картинка уменьшается до
   * значка (64 точки), весит килобайты и должна переезжать вместе с
   * настройками — файл в стороне отвязался бы от них при переносе.
   *
   * Пусто — рисуется буквенная пометка на цветном поле, как у встроенных
   * видов без своего рисунка. Поэтому пометка и цвет обязательны и при
   * заданной картинке: они остаются запасным обозначением.
   */
  readonly iconDataUrl: string | null;
  readonly placements: readonly CustomElementPlacement[];
  readonly fields: readonly CustomField[];
  readonly note: string | null;
  readonly createdAt: IsoDateTime;
  readonly updatedAt: IsoDateTime;
  /**
   * Вид выведен из обращения.
   *
   * Физически вид не удаляется: на него ссылаются заведённые объекты и записи
   * журнала, а журнал эксплуатации не правится задним числом. Выведенный вид
   * пропадает из библиотеки, но карточки и история остаются читаемыми.
   */
  readonly archivedAt: IsoDateTime | null;
}
