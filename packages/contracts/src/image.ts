/**
 * Изображение в памяти и операции очистки подложки.
 *
 * Очистка нужна, потому что планы приходят «с нагрузкой»: стрелки эвакуации,
 * уже расставленные значки огнетушителей, легенда, экспликация, штамп, рамка.
 * Для работы нужна голая архитектура — стены, проёмы, лестницы, — на которую
 * программа сама нанесёт оборудование.
 *
 * Очистка неразрушающая. Исходное изображение остаётся в хранилище нетронутым,
 * а список операций сохраняется отдельно, чтобы очистку можно было повторить,
 * поправить или отменить целиком.
 */

import type { ContentHash, IsoDateTime, PixelPoint, PixelRect } from './basic-types.js';

export const CLEANUP_ENGINE_VERSION = '2026-08-20-crop-first-monochrome';

export interface RgbColor {
  readonly r: number;
  readonly g: number;
  readonly b: number;
}

/** Изображение в памяти: четыре байта на точку, красный-зелёный-синий-прозрачность. */
export interface RgbaImage {
  readonly widthPx: number;
  readonly heightPx: number;
  readonly data: Uint8ClampedArray;
}

/**
 * Область на чертеже: прямоугольник или обводка от руки.
 *
 * Прямоугольником берут прямоугольное — штамп, таблицу, угол листа.
 * Обводкой — всё остальное: стрелки эвакуации вдоль коридора, крыльцо,
 * соседний цех за ломаной стеной.
 */
export type EraseArea =
  | { readonly kind: 'rect'; readonly rect: PixelRect }
  | { readonly kind: 'polygon'; readonly points: readonly PixelPoint[] };

/**
 * Одно действие очистки.
 *
 * Действия применяются по порядку. Каждое из них — чистая функция над
 * изображением, поэтому результат всегда воспроизводим.
 */
export type CleanupOperation =
  /** Обрезка: оставить только выбранный прямоугольник. Убирает рамку и штамп. */
  | { readonly kind: 'crop'; readonly rect: PixelRect }
  /** Стереть прямоугольник. Убирает легенду, экспликацию, таблицы. */
  | { readonly kind: 'erase-rect'; readonly rect: PixelRect }
  /**
   * Стереть область произвольной формы.
   *
   * Прямоугольником убирается не всё. Штамп в углу вырезается рамкой, а вот
   * соседний цех, примыкающий к нужному по ломаной стене, — нет: прямоугольник
   * захватил бы половину своего здания. Поэтому обводка от руки — границу ведут
   * по тому, что видно на чертеже.
   *
   * Точки замыкаются в многоугольник; меньше трёх точек стирать нечего.
   */
  | { readonly kind: 'erase-polygon'; readonly points: readonly PixelPoint[] }
  /** Убрать один конкретный цвет с допуском. Выбирается щелчком по палитре плана. */
  | { readonly kind: 'remove-color'; readonly color: RgbColor; readonly tolerance: number }
  /**
   * Убрать всё цветное, оставив только чёрные и серые линии здания.
   *
   * Главное действие для планов эвакуации. Устроено сложнее, чем «убрать
   * насыщенные точки», потому что этого недостаточно:
   *
   * - края линий на плане сглажены, вокруг зелёной стрелки остаётся бледная
   *   кайма с почти нулевой насыщенностью. Если убрать только яркое, на месте
   *   стрелки останется её призрак. Для этого есть haloRadiusPx;
   * - значок огнетушителя — красная заливка в чёрной обводке. Обводка по цвету
   *   не отличается от стены, и после удаления красного остаётся пустая рамка.
   *   Для этого есть symbolGrowthPx: удаление прорастает от цветных точек в
   *   соседний рисунок на ограниченное число шагов и снимает обводку.
   *
   * Ограничение по числу шагов принципиально. Если убирать связную фигуру
   * целиком, то стрелка, коснувшаяся стены, утащит за собой и стену: они
   * образуют одну связную фигуру. С ограничением стена теряет лишь несколько
   * точек в месте касания.
   */
  | {
      readonly kind: 'remove-colored';
      /** Относительная насыщенность, от 0 до 1. Меньше — убирается больше. */
      readonly saturationThreshold: number;
      /** Расширение маски наружу, чтобы снять кайму сглаживания. */
      readonly haloRadiusPx: number;
      /** На сколько точек удаление прорастает в соседний рисунок. 0 — не прорастает. */
      readonly symbolGrowthPx: number;
    }
  /**
   * Убрать одну фигуру, на которую указал пользователь.
   *
   * Действует и на одноцветных чертежах, где значки нарисованы тем же чёрным,
   * что и стены: там цвет не помогает, а щелчок по значку — помогает.
   */
  | {
      readonly kind: 'remove-component';
      readonly seed: PixelPoint;
      /** Фигуры крупнее этой доли площади не убираются: это стены. */
      readonly maxShare: number;
      /** Удаление не уходит дальше этого расстояния от точки щелчка. */
      readonly maxRadiusPx: number;
    }
  /**
   * Убрать мелкие текстоподобные элементы: подписи помещений, боковые и верхние
   * надписи, мелкие служебные обозначения.
   *
   * Это эвристика для подготовки подложки. Крупные линии здания и длинные
   * размерные/стеновые линии должны сохраняться.
   */
  | {
      readonly kind: 'remove-small-components';
      readonly maxWidthPx: number;
      readonly maxHeightPx: number;
      readonly maxPixels: number;
    }
  /** Оставить только тёмное. Убирает светлую заливку, штриховку и подложечную серость. */
  | { readonly kind: 'keep-dark'; readonly luminanceThreshold: number }
  /**
   * Повернуть чертёж на четверть оборота.
   *
   * Планы приходят лежащими на боку: лист альбомный, а сканировали книжной
   * стороной, или чертёж выгружен повёрнутым. Разбирать такой план, наклонив
   * голову, нельзя — на нём расставляют оборудование.
   *
   * Только кратно прямому углу, и это не упрощение. При повороте на 90°
   * каждая точка переезжает в другую точку без остатка, и чертёж не теряет
   * ни одной линии. Поворот на произвольный угол пришлось бы досчитывать
   * между точками: тонкие стены стали бы серыми и размытыми, а на плане по
   * ним меряют расстояния.
   */
  | { readonly kind: 'rotate'; readonly quarterTurns: 1 | 2 | 3 }
  /**
   * Нарисовать линию поверх чертежа.
   *
   * Чертежи приходят не только с лишним, но и с недостающим: перегородку
   * поставили после выпуска плана, проём заложили, кладовку разделили надвое.
   * Стереть такое нечем — там нечего стирать, — а без линии план врёт.
   *
   * Ломаная, а не отрезок: прямую рисуют двумя точками, от руки — многими, и
   * различать их в хранимом действии незачем. Толщина в точках чертежа, а не
   * экрана: линия принадлежит плану и растёт вместе с ним при приближении.
   */
  | {
      readonly kind: 'draw-line';
      readonly points: readonly PixelPoint[];
      readonly color: string;
      readonly widthPx: number;
    }
  /**
   * Убрать цветное внутри указанной области.
   *
   * Для планов эвакуации, где цветные стрелки идут поверх планировки. Убрать
   * цвет по всему листу нельзя: цветом бывают нарисованы и нужные вещи —
   * лестницы, номера помещений, сама планировка на цветной выкопировке.
   * Стереть область целиком тоже нельзя: под стрелкой лежит стена.
   *
   * Поэтому область ограничивает вред, а цвет выбирает жертву: внутри
   * обведённого гибнут только цветные точки, чёрные линии здания остаются.
   *
   * color задан — убирается он один с допуском (щёлкнули по фиолетовой
   * стрелке — уйдёт фиолетовое). color пуст — убирается всё насыщенное
   * внутри области.
   */
  | {
      readonly kind: 'erase-colored-in-area';
      readonly area: EraseArea;
      readonly color: RgbColor | null;
      /** Допуск по каждой составляющей цвета, 0…255. Действует, когда цвет задан. */
      readonly tolerance: number;
      /** Относительная насыщенность, 0…1. Действует, когда цвет не задан. */
      readonly saturationThreshold: number;
      /** Расширение маски наружу, чтобы снять бледную кайму сглаживания. */
      readonly haloRadiusPx: number;
    };

/** Сохранённая очистка подложки. */
export interface BackdropCleanup {
  readonly backdropId: string;
  /** Версия алгоритма очистки. Старые результаты нужно пересчитать, а не молча показывать. */
  readonly engineVersion?: string;
  readonly operations: readonly CleanupOperation[];
  /** Очищенное изображение в хранилище. */
  readonly cleanedImageHash: ContentHash;
  readonly widthPx: number;
  readonly heightPx: number;
  readonly updatedAt: IsoDateTime;
}

/** Запись палитры плана: цвет и какую долю точек он занимает. */
export interface PaletteEntry {
  readonly color: RgbColor;
  /** Доля от всех точек изображения, от 0 до 1. */
  readonly share: number;
}
