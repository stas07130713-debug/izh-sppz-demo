/**
 * Дерево объекта — структура предприятия, к которой привязано всё остальное.
 *
 * Организация → цех → здание → этаж. Внутри здания, наряду с этажами, заводятся
 * склады: туда попадает оборудование, которое учитывается, но не установлено на
 * месте — запасные огнетушители, снятое на перезарядку, а также всё, что
 * числится за пожарной техникой. Отдельной сущности «Техника» в программе нет:
 * это частный случай склада, а исключения в структуре данных не заводятся.
 *
 * Планы принадлежат узлам: у здания — генплан объекта с гидрантами, наружными
 * лестницами и местами подключения пожарной техники; у этажа — поэтажный план
 * с системами противопожарной защиты; у склада — окно склада без координат.
 *
 * Все виды узлов лежат в одной таблице с полем kind. Причина — конструктор:
 * пользователь должен заводить свои виды узлов без программиста, а это
 * невозможно, если каждому виду соответствует своя таблица. Правила вложенности
 * заданы данными, см. tree-rules.ts в ядре.
 *
 * Смотри docs/02_ТЗ_редакция_3.md, часть 3.
 */

import type { IsoDateTime } from './basic-types.js';
import type { Result } from './result.js';

/** UUID узла дерева. */
export type TreeNodeId = string;

/**
 * Вид узла дерева.
 *
 * Строки, а не числа: коды видов попадут в обмен данными и в пакеты правил, где
 * порядковые номера ломаются при слиянии справочников с разных узлов.
 */
export type NodeKind =
  /** Организация или предприятие — корень дерева. */
  | 'organization'
  /** Цех — группировка зданий. Необязателен: здание можно завести прямо в организации. */
  | 'shop'
  /** Здание или сооружение. Его рабочая область — генплан объекта. */
  | 'building'
  /** Этаж или отметка. Рабочая область — поэтажный план. */
  | 'level'
  /** Склад: запасное оборудование, снятое на перезарядку, числящееся за техникой. */
  | 'storage';

/**
 * Характеристики здания в части пожарной безопасности.
 *
 * От этих значений зависят нормативные требования, поэтому в интерфейсе они
 * заполняются выпадающими списками, а не вводом текста: опечатка здесь исказит
 * выводы программы. Сами списки значений — данные, см. building-profile.ts.
 *
 * Все поля необязательные: сведения о старом здании собираются постепенно, и
 * незаполненная характеристика не должна мешать вести журнал. Здание с
 * пробелами помечается в дашборде состояния объекта.
 */
export interface BuildingProfile {
  /**
   * Классы функциональной пожарной опасности: Ф1.1 … Ф5.3.
   *
   * Значений может быть несколько: здание нередко совмещает административную
   * часть Ф4.3 и производственную Ф5.1. Хранятся в одном поле через запятую.
   */
  readonly functionalClasses: string | null;
  /** Степень огнестойкости: I … V. */
  readonly fireResistance: string | null;
  /** Класс конструктивной пожарной опасности: С0 … С3. */
  readonly constructiveClass: string | null;
  readonly floorsAbove: number | null;
  readonly floorsBelow: number | null;
  readonly heightM: number | null;
  readonly builtAreaM2: number | null;
  readonly volumeM3: number | null;
  /**
   * Категория здания по взрывопожарной и пожарной опасности: А, Б, В, Г, Д.
   *
   * Без В1–В4: по СП 12.13130 на эти классы делятся помещения, а не здание.
   * Категории помещений живут в карточке помещения, см. rooms.ts.
   */
  readonly explosionCategory: string | null;
  /** Документ, которым определена категория. Программа категорию не рассчитывает. */
  readonly categoryBasis: string | null;
  /**
   * Классы возможного пожара на объекте: A, B, C, D, E.
   *
   * В информационных справках он указывается на здание целиком — «класс
   * возможного пожара на объекте: А, В, Е», — и по нему выбирается ранг
   * тушения (ППР, приложение № 1). Помещение может уточнить его своим
   * списком, см. rooms.ts. Значений несколько, хранятся через запятую.
   */
  readonly fireClasses: string | null;
  /** Наличие чердака. */
  readonly attic: string | null;
  /** Наличие мансардного этажа. */
  readonly mansardFloor: string | null;
  readonly evacuationExits: number | null;
  readonly builtYear: number | null;
  readonly responsible: string | null;
}

/**
 * Узел дерева объекта.
 *
 * Поля created/updated и rowVersion заполняются с первого дня, хотя пользователь
 * пока один: в многопользовательском режиме их нечем заполнить задним числом, а
 * без rowVersion правки двух пользователей молча затрут друг друга.
 */
export interface TreeNode {
  readonly id: TreeNodeId;
  /** Организация, которой принадлежит узел. У самой организации равен её же id.
   *  Нужен для разграничения доступа и выборок, когда один сервер ведёт несколько организаций. */
  readonly siteId: TreeNodeId;
  /** Родитель. У организации — null. */
  readonly parentId: TreeNodeId | null;
  readonly kind: NodeKind;
  readonly name: string;
  /** Справочный код: инвентарный номер здания, номер цеха, госномер машины для склада техники. */
  readonly code: string | null;
  /** Отметка этажа в метрах, со знаком: −3.6 для подвала. Только для kind = 'level'. */
  readonly elevationM: number | null;
  readonly note: string | null;
  /** Характеристики в части ПБ. Заполняются только у здания. */
  readonly building: BuildingProfile | null;
  /** Порядок среди соседей. Пользователь расставляет этажи так, как ему привычно. */
  readonly sortOrder: number;
  /**
   * Показывать ли содержимое узла в общем журнале здания.
   *
   * Запасные огнетушители со склада не нужны в журнале по конкретному этажу, но
   * нужны в инвентарной ведомости. Отключение влияет только на состав
   * представления: записи остаются на месте и продолжают учитываться в сроках.
   */
  readonly inCommonJournal: boolean;
  /**
   * Закреплены ли объекты на плане этого узла (ТЗ, Дополнение 3, часть К5).
   *
   * Свойство плана, а не текущего сеанса работы: пользователь закрепил
   * расстановку — она остаётся закреплённой при переходе на другой этаж и
   * обратно, при переходе в журнал и обратно, и после перезапуска программы.
   * Снимает закрепление только явное нажатие «Раскрепить» на этом же плане.
   */
  readonly objectsPinned: boolean;
  /**
   * Когда узел выведен из эксплуатации.
   *
   * Физического удаления в программе нет: журнал эксплуатации предъявляется при
   * проверке, и история снесённого здания должна остаться доступной.
   */
  readonly archivedAt: IsoDateTime | null;
  readonly createdAt: IsoDateTime;
  readonly updatedAt: IsoDateTime;
  /** Растёт на единицу при каждой записи. Основа оптимистической блокировки. */
  readonly rowVersion: number;
}

/**
 * Хранение дерева объекта.
 *
 * Удаления в порте нет намеренно: вывод узла из эксплуатации — это обычная
 * запись с заполненным archivedAt. Так правило «историю не удаляем» держится
 * устройством программы, а не памятью разработчика.
 */
export interface ObjectTreeRepository {
  /** Все узлы всех организаций, включая выведенные из эксплуатации. */
  list(): Promise<Result<readonly TreeNode[]>>;
  getById(id: TreeNodeId): Promise<Result<TreeNode>>;
  save(node: TreeNode): Promise<Result<void>>;
}
