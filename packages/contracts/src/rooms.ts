/**
 * Помещения этажа.
 *
 * Помещение принадлежит этажу и нигде больше: категория по взрывопожарной
 * опасности и площадь — свойства помещения, а не здания и не склада.
 *
 * Обводка хранится в точках подложки, а не в метрах. Причина: подложку можно
 * перекалибровать, если масштаб задали неточно, и тогда площадь пересчитается
 * сама, а обводка останется на прежнем месте чертежа. Если бы хранились метры,
 * перекалибровка сдвинула бы все помещения.
 *
 * Смотри docs/02_ТЗ_редакция_3.md, часть 5.5.
 */

import type { IsoDateTime, PixelPoint } from './basic-types.js';
import type { TreeNodeId } from './object-tree.js';
import type { Result } from './result.js';

export type RoomId = string;

export interface Room {
  readonly id: RoomId;
  /** Организация, которой принадлежит помещение. Как и у узлов дерева. */
  readonly siteId: TreeNodeId;
  /** Этаж. Помещение существует только внутри этажа. */
  readonly levelId: TreeNodeId;
  readonly name: string;
  /** Номер по экспликации. */
  readonly number: string | null;
  /** Категория по взрывопожарной и пожарной опасности: А, Б, В1 … В4, Г, Д. */
  readonly category: string | null;
  /** Документ, которым определена категория. Программа категорию не рассчитывает. */
  readonly categoryBasis: string | null;
  /**
   * Назначение помещения: производственное, складское, административное,
   * общественное.
   *
   * От него зависит расстояние до огнетушителя — ППР задаёт 20 метров для
   * административных и общественных помещений независимо от категории — и
   * потребность в передвижных огнетушителях, которая есть только у
   * производственных и складских.
   */
  readonly purpose: string | null;
  /**
   * Классы возможного пожара: A, B, C, D, E.
   *
   * По ним выбирается ранг тушения (ППР, приложение № 1). В справках заказчика
   * класс указан на здание целиком («класс возможного пожара на объекте: А, В,
   * Е»), но по помещениям он различается, поэтому хранится у помещения.
   */
  readonly fireClasses: readonly string[];
  /**
   * Помещение защищено автоматической установкой пожаротушения.
   *
   * Такие помещения обеспечиваются огнетушителями на 50 процентов расчётного
   * количества (ППР, пункт 409), при этом норма расстояния сохраняется.
   */
  readonly hasSuppression: boolean;
  /** Высота помещения: от неё зависят правила размещения извещателей. */
  readonly heightM: number | null;
  /** Обводка по углам помещения в точках подложки. null — помещение ещё не отмечено на плане. */
  readonly outline: readonly PixelPoint[] | null;
  /** Площадь, вычисленная по обводке и масштабу плана. Пользователь её не вводит. */
  readonly areaM2: number | null;
  readonly archivedAt: IsoDateTime | null;
  readonly createdAt: IsoDateTime;
  readonly updatedAt: IsoDateTime;
  readonly rowVersion: number;
}

/**
 * Хранение помещений.
 *
 * Удаления нет по той же причине, что и у дерева: история не удаляется никогда.
 */
export interface RoomRepository {
  listByLevel(levelId: TreeNodeId): Promise<Result<readonly Room[]>>;
  /** Все помещения организации — журналу выше уровня этажа нужны названия чужих этажей. */
  list(): Promise<Result<readonly Room[]>>;
  getById(id: RoomId): Promise<Result<Room>>;
  save(room: Room): Promise<Result<void>>;
}
