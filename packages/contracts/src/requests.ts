/**
 * Заявка на внешний подряд (ТЗ, Дополнение 6, часть С54).
 *
 * Заявка — это список оборудования, который отдают подрядчику, и вид у неё на
 * каждом предприятии свой: где-то нужен заводской номер, где-то место и
 * характер неисправности. Поэтому состав граф задаёт пользователь, а программа
 * помнит его шаблоном и подставляет данные из журнала.
 */

/** Одна графа заявки. */
export interface RequestColumn {
  /** Заголовок графы в документе — его пишет пользователь. */
  readonly title: string;
  /**
   * Откуда берётся значение.
   *
   * Название графы из каталога — значение подставляется из журнала. `'свой'` —
   * графа остаётся пустой: её заполняют от руки уже в документе. Своё значение
   * намеренно не подставляется ниоткуда, иначе оно было бы не своим.
   */
  readonly source: string;
}

export interface RequestTemplate {
  readonly id: string;
  /** Название шаблона в списке. */
  readonly title: string;
  /** Заголовок самого документа заявки. */
  readonly documentTitle: string;
  /** Для какого вида оборудования заготовлен шаблон; null — для любого. */
  readonly typeCode: string | null;
  readonly columns: readonly RequestColumn[];
  /** Строки под таблицей: должности, подписи, дата. */
  readonly footer: readonly string[];
  readonly createdAt: string;
}
