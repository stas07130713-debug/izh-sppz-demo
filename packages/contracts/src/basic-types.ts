/**
 * Простые общие типы: идентификаторы, даты, точки и прямоугольники.
 *
 * Идентификаторы — обычные строки с UUID внутри. Целочисленные автоинкрементные
 * ключи запрещены: программа должна работать на сервере с несколькими
 * пользователями, где такие ключи дают конфликты.
 */

/** UUID подложки плана. */
export type BackdropId = string;

/** Календарная дата без времени и часового пояса, формат ГГГГ-ММ-ДД.
 *  Используется для регламентных дат: «проверка 12.05.2026» не должна
 *  сдвигаться из-за часового пояса пользователя. */
export type IsoDate = string;

/** Момент времени в UTC, формат ISO 8601. Используется для служебных отметок. */
export type IsoDateTime = string;

/** SHA-256 содержимого файла в шестнадцатеричном виде. Адрес файла в хранилище. */
export type ContentHash = string;

/** Точка в пикселях изображения подложки. Начало координат — левый верхний угол. */
export interface PixelPoint {
  readonly x: number;
  readonly y: number;
}

/** Размер в пикселях. */
export interface PixelSize {
  readonly widthPx: number;
  readonly heightPx: number;
}

/** Прямоугольник в пикселях изображения подложки. */
export interface PixelRect {
  readonly x: number;
  readonly y: number;
  readonly widthPx: number;
  readonly heightPx: number;
}

/** Поворот, кратный 90 градусам. Другие углы не поддерживаются намеренно:
 *  планы приходят повёрнутыми только на прямой угол. */
export type QuarterTurn = 0 | 90 | 180 | 270;
