/**
 * Сведения карточки модульной автономной установки пожаротушения
 * (ТЗ, Дополнение 6).
 *
 * Установка срабатывает без прибора управления, поэтому в её карточке должно
 * быть записано всё, чем она отличается: чем тушит, что защищает, как
 * запускается и как обнаруживает пожар. По этим сведениям её проверяют и
 * подбирают замену.
 */
export interface SuppressionProfile {
  /** Что защищает установка: помещение, оборудование, шкаф и так далее. */
  readonly protectedZone: string | null;
  /**
   * Способы пуска. Их бывает несколько сразу: автоматический пуск с
   * электрическим приводом и резервный ручной местный — обычное сочетание.
   * Поэтому список, а не одно значение.
   */
  readonly startModes: readonly string[];
  /** Как установка обнаруживает пожар: тепловое, дымовое, пламени, иное. */
  readonly detection: string | null;
}

/**
 * Резервное питание прибора (ТЗ, Дополнение 6).
 *
 * Аккумулятор — то, чем система живёт при пропадании сети, и первое, что
 * спрашивает проверяющий. Ёмкость и количество нужны вместе: время работы
 * системы считается по их произведению, и одна цифра без другой ничего не
 * говорит.
 */
export interface BackupPowerProfile {
  /**
   * Чем запитан прибор при пропадании сети: аккумуляторная батарея, источник
   * бесперебойного питания, отдельная линия — или резервного питания нет.
   *
   * Выбором, а не галочкой «есть/нет»: галочка отвечает только на один вопрос
   * и не отличает «резервного питания нет» от «ещё не выяснили», а это разные
   * сведения — одно закрывает вопрос, другое оставляет его открытым.
   */
  readonly source: string | null;
  /** Тип аккумулятора: свинцово-кислотный AGM, гелевый, литий-железо-фосфатный, иной. */
  readonly batteryKind: string | null;
  /** Ёмкость одного аккумулятора, ампер-часов. */
  readonly capacityAh: number | null;
  /** Сколько аккумуляторов установлено. */
  readonly count: number | null;
}

/**
 * Сведения карточки прибора приёмно-контрольного (ТЗ, Дополнение 6).
 *
 * Прибор — голова системы пожарной автоматики, и его карточка отвечает за всю
 * систему: состав, резервное питание, рабочая документация. Отдельной карточки
 * «система» нет — она была бы вторым местом для тех же сведений.
 */
export interface ControlPanelProfile {
  /**
   * Исполнение: ППКП — только приём и контроль, ППКУ — ещё и управление
   * (пожаротушением, дымоудалением, оповещением). Различие не формальное: от
   * него зависит и состав системы, и объём проверок.
   */
  readonly execution: 'ППКП' | 'ППКУ' | null;
  readonly backupPower: BackupPowerProfile | null;
  /**
   * Рабочая и проектная документация по системе противопожарной защиты.
   *
   * Хранится у прибора, а не у каждого извещателя: проект один на систему, и
   * класть его копию в каждую карточку значило бы плодить расхождения.
   */
  readonly projectDocuments: readonly StoredDocumentReference[];
}

/**
 * Сведения карточки пожарного крана.
 *
 * Ровно те четыре величины, по которым кран подбирают и обслуживают: без них
 * нельзя ни проверить водоотдачу, ни подобрать рукав на замену. Всё остальное —
 * марка, изготовитель, серийный номер — у крана в паспорте объекта не ведут, и
 * пустые графы в карточке только мешали бы.
 *
 * Значения свободные строкой, а не перечислением: заказчик называет обычные —
 * Ду 50, Ду 65 — но встречается и «Другое», и записать туда надо то, что стоит
 * на объекте, а не ближайшее из списка.
 */
export interface HydrantProfile {
  /** Условный проход пожарного клапана: Ду 50, Ду 65 или иной. */
  readonly valveBore: string | null;
  /** Диаметр пожарного рукава: 51 мм, 66 мм или иной. */
  readonly hoseDiameter: string | null;
  /** Соединительная головка (полугайка): ГР-50, ГР-70 или иная. */
  readonly couplingHead: string | null;
  /** Диаметр спрыска пожарного ствола: 13, 16, 19 мм или иной. */
  readonly nozzleBore: string | null;
}

/**
 * Сведения карточки огнезащитной обработки (ТЗ, Дополнение 6).
 *
 * Огнезащита — не изделие на стене, а состояние конструкции: её нанесли, у неё
 * есть срок действия, и по его истечении её возобновляют. Поэтому здесь нет ни
 * заводского номера, ни срока службы по паспорту — есть обработанная
 * конструкция, состав, дата обработки и до какого числа она действует.
 */
export interface FireproofingProfile {
  /** Что обработано: несущие металлоконструкции, деревянные конструкции, кабель. */
  readonly structure: string | null;
  /** Вид огнезащиты: пропитка, покрытие, обмазка, облицовка, конструктивная. */
  readonly treatmentKind: string | null;
  /** Марка огнезащитного состава. */
  readonly material: string | null;
  /** Изготовитель состава. */
  readonly manufacturer: string | null;
  /** Обработанная площадь, квадратных метров. */
  readonly areaM2: number | null;
  /**
   * Требуемый предел огнестойкости или группа огнезащитной эффективности.
   *
   * Строкой: обозначения разнородны — «R 45» у конструкций и «2-я группа» у
   * деревянных, — и приводить их к одному виду значило бы потерять смысл.
   */
  readonly requirement: string | null;
  /** Дата выполнения обработки. */
  readonly treatedOn: IsoDate | null;
  /**
   * Срок действия обработки по документации изготовителя, лет.
   *
   * Именно он, а не срок службы: состав держится столько, сколько обещал
   * изготовитель, и по истечении обработку возобновляют заново.
   */
  readonly warrantyYears: number | null;
  /** Кто выполнял обработку. */
  readonly performer: string | null;
}

