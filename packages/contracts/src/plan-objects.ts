/**
 * Объекты систем противопожарной защиты.
 *
 * Объект и запись журнала — одно и то же. Отдельной таблицы объектов у плана
 * нет: значок на плане и строка в журнале читаются из одной записи, поэтому
 * расхождение между ними невозможно по устройству, а не по дисциплине
 * разработчика.
 *
 * Координаты хранятся в точках подложки — по той же причине, что и обводки
 * помещений: подложку можно перекалибровать, и объекты останутся на своих
 * местах чертежа.
 *
 * Смотри docs/02_ТЗ_редакция_3.md, часть 7.
 */

