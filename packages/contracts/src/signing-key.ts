/**
 * Ключ простой электронной подписи пользователя (вариант Б).
 *
 * Заказчик выбрал решение с ключом у каждого подписывающего. Разница с
 * подписью «одним паролем» такая: там подтверждением служил сам факт, что
 * программа сверила пароль, и доказательство жило внутри программы. Здесь
 * подпись — величина, которую можно проверить снаружи: открытым ключом, не зная
 * ни пароля, ни устройства программы.
 *
 * Устройство:
 *
 *  - при задании пароля пользователю заводится пара ключей Ed25519;
 *  - открытый ключ лежит в учётной записи открыто — он на то и открытый;
 *  - закрытый зашифрован паролем: программа не может подписать за человека,
 *    потому что расшифровать ключ без пароля нечем. Пароль хранится отпечатком
 *    и в расшифровке не участвует — ключ шифрования выводится из самого пароля
 *    отдельным scrypt со своей солью;
 *  - смена пароля перешифровывает ключ, а поколение растёт. Прежние подписи
 *    остаются проверяемыми: открытый ключ у них тот же.
 *
 * Забытый пароль означает потерю закрытого ключа: администратор выдаёт
 * временный пароль, человек задаёт новый — и получает **новую** пару. Прежние
 * подписи проверяются прежним открытым ключом, который хранится в самой
 * подписи. Иначе восстановление пароля означало бы возможность подписать
 * задним числом за другого.
 */

import type { Result } from './result.js';

/** Зашифрованный паролем закрытый ключ и его открытая часть. */
export interface SigningKey {
  readonly algorithm: 'ed25519';
  /** Открытый ключ, base64. Им проверяют подпись — он не секрет. */
  readonly publicKey: string;
  /** Закрытый ключ, зашифрованный AES-256-GCM на ключе из пароля. base64. */
  readonly encryptedPrivateKey: string;
  /** Вектор инициализации шифра, base64. */
  readonly iv: string;
  /** Метка подлинности шифра (GCM tag), base64. */
  readonly authTag: string;
  /** Соль для вывода ключа шифрования из пароля, base64. */
  readonly salt: string;
  /** Поколение: растёт при каждой смене пароля вместе с `keyGeneration`. */
  readonly generation: number;
}

/**
 * Криптографическая часть подписи.
 *
 * Хранится внутри самой подписи (63-ФЗ, статья 9 часть 1: подпись содержится в
 * документе), вместе с открытым ключом — чтобы проверить её можно было и после
 * того, как человек сменил ключ или уволился.
 */
export interface KeySignature {
  readonly algorithm: 'ed25519';
  /** Подпись отпечатка содержимого, base64. */
  readonly value: string;
  /** Открытый ключ подписавшего на момент подписания, base64. */
  readonly publicKey: string;
}

/**
 * Кто умеет обращаться с ключами подписи.
 *
 * Порт, а не готовая реализация: криптография живёт в главном процессе (там
 * `node:crypto`), а сценарии ядра о ней знать не должны — им довольно
 * обещания «заведи ключ», «подпиши», «проверь».
 */
export interface SigningKeyService {
  /** Заводит новую пару и запирает закрытый ключ паролем. */
  create(password: string, generation: number): Promise<Result<SigningKey>>;
  /**
   * Перешифровывает закрытый ключ на новый пароль.
   *
   * Нужна при смене пароля: пара остаётся прежней, значит и прежние подписи
   * проверяются тем же открытым ключом.
   */
  rekey(key: SigningKey, oldPassword: string, newPassword: string, generation: number): Promise<Result<SigningKey>>;
  /** Подписывает отпечаток содержимого. Пароль нужен, чтобы отпереть ключ. */
  sign(key: SigningKey, password: string, contentHash: string): Promise<Result<KeySignature>>;
  /** Проверяет подпись отпечатка. Пароль не нужен: проверяют открытым ключом. */
  verify(signature: KeySignature, contentHash: string): Promise<Result<boolean>>;
}
