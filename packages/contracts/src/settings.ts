/**
 * Настройки программы.
 *
 * Смотри docs/02_ТЗ_редакция_3.md, Дополнение 1, часть Д11: «Порог «скоро»
 * должен быть настраиваемым» — у разных предприятий разный запас времени на
 * реакцию, и жёстко зашитое число было бы решением за пользователя.
 *
 * Поля лежат плоско, без вложенных разделов: хранилище дополняет прочитанное
 * значениями по умолчанию одним слиянием верхнего уровня, и вложенный раздел
 * пришёл бы из старого файла наполовину пустым.
 */

import type { Result } from './result.js';
import type { RequestTemplate } from './requests.js';
import type { CustomElementType } from './custom-elements.js';

export interface AppSettings {
  /** За сколько дней до просрочки статус становится «скоро». */
  readonly soonThresholdDays: number;
  /** Формат, предлагаемый первым при выгрузке карточки огнетушителя. */
  readonly defaultExtinguisherCardFormat: 'pdf' | 'word' | 'excel';
  /**
   * Состав дашборда: какие блоки показывать и в каком порядке.
   *
   * Включённость и порядок — один список: блок включён, если он в списке.
   * Отдельное поле «включён» рядом с отдельным полем «место» разошлось бы при
   * первой же правке. Названия блоков и рекомендуемый состав знает ядро.
   */
  readonly dashboardBlocks: readonly string[];
  /**
   * Шаблоны заявок на внешний подряд.
   *
   * Лежат в настройках, а не в своём хранилище: это заготовки оформления, а не
   * учётные записи — их не версионируют и на них не ссылается журнал.
   */
  readonly requestTemplates: readonly RequestTemplate[];
  /**
   * Свои виды противопожарных элементов (движок E4).
   *
   * Лежат в настройках, а не в отдельном хранилище, по той же причине, что
   * и шаблоны заявок: это настройка программы, а не учётная запись. На них
   * не ссылается журнал записями, их не версионируют, и их горстка.
   */
  readonly customElements: readonly CustomElementType[];
  /**
   * Свои значки для встроенных видов: код вида → картинка `data:`.
   *
   * Заказчик: «нужно сделать возможность пользователю самостоятельно менять
   * и назначать значки на системы, какие ему будет удобно». Обозначения на
   * планах у предприятий свои — принятые в проектной документации или в
   * инструкциях, — и навязывать наши незачем.
   *
   * Здесь только замены. Вид, которого тут нет, рисуется своим встроенным
   * значком: хранить копию всего набора значило бы возить с настройками
   * два мегабайта картинок, которые и так лежат в программе.
   */
  readonly elementIcons: Readonly<Record<string, string>>;

  /**
   * Свои названия встроенных видов оборудования: код вида → название.
   *
   * Заказчик: «добавь, чтобы можно было заменять не только сами значки, но и
   * название этих систем». На предприятии оборудование зовут по-своему, и наши
   * слова ему навязывать незачем.
   *
   * Здесь только замены: вида, которого тут нет, зовут как в каталоге. Меняется
   * лишь показываемое название — код вида, правила и справочники остаются
   * прежними, иначе переименование рвало бы связь с нормативом.
   */
  readonly elementTitles: Readonly<Record<string, string>>;
  /**
   * Состав таблицы журнала по видам оборудования.
   *
   * Заказчик: «вкладка журнал должна сразу отображать три основные функции:
   * 1 — возможность изменять состав таблицы относительно каждого элемента».
   *
   * Ключ — код вида, значение — **убранные** графы. Убранные, а не
   * оставленные, по двум причинам. Пустая запись означает «всё как есть», и
   * настройка не требуется никому, кто её не трогал. И новая графа, которая
   * появится в программе завтра, покажется сама: список оставленных её бы не
   * содержал, и она молча пропала бы у всех, кто когда-то что-то настроил.
   *
   * Графы проверок сюда не входят: их состав задаёт регламент — соседняя
   * настройка на той же вкладке. Убрать работу из журнала настройкой вида
   * значило бы спрятать обязанность, а не графу.
   */
  readonly journalColumns: Readonly<Record<string, readonly string[]>>;
}

export const DEFAULT_APP_SETTINGS: AppSettings = {
  soonThresholdDays: 14,
  defaultExtinguisherCardFormat: 'pdf',
  dashboardBlocks: [
    'показатель-всего',
    'показатель-норма',
    'показатель-скоро',
    'показатель-неисправно',
    'показатель-нет-данных',
    'график-системы',
    'график-состояние',
    'график-по-видам',
    'сроки-то',
  ],
  requestTemplates: [],
  customElements: [],
  elementIcons: {},
  elementTitles: {},
  journalColumns: {},
};

export interface AppSettingsRepository {
  get(): Promise<Result<AppSettings>>;
  save(settings: AppSettings): Promise<Result<void>>;
}
