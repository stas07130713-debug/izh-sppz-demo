/**
 * Учётные записи, роли и права доступа.
 *
 * Разграничение решает три задачи, и только их стоит от него ждать:
 *
 *  1. каждый видит своё. Ответственный за здание не правит чужой цех по ошибке;
 *  2. у действия есть автор. Без этого журнал изменений и простая электронная
 *     подпись невозможны: подписывать некому;
 *  3. настройки, общие для всей организации — периодичность регламентных работ,
 *     параметры программы — меняет один человек, а не каждый по-своему.
 *
 * Чего от него ждать нельзя, пока программа локальная: защиты от того, кто
 * сознательно откроет файлы данных мимо программы. Данные лежат в профиле
 * Windows, и прочитать их может любой, у кого есть доступ к этому профилю.
 * Настоящее разграничение появится вместе с серверной частью; форма учётной
 * записи и права рассчитаны на неё и не изменятся.
 *
 * Пароль нигде не хранится. Хранится только его отпечаток, по которому пароль
 * не восстанавливается, — поэтому «пароль доступен только этому пользователю»
 * выполняется буквально: его не знает и администратор.
 */

import type { IsoDateTime } from './basic-types.js';
import type { TreeNodeId } from './object-tree.js';
import type { Result } from './result.js';
import type { SigningKey } from './signing-key.js';

export type UserId = string;

/**
 * Роли.
 *
 * Их ровно три, и они не пересекаются: у каждой свой круг задач, а не «больше
 * прав — меньше прав». Ответственный за ПБ не «администратор поменьше»: он
 * ведёт свой объект целиком, но не задаёт правила, общие для организации.
 */
export type UserRole =
  /** Ведёт программу: люди, права, общие настройки, регламенты, журнал изменений. */
  | 'администратор'
  /** Ведёт порученные объекты: оборудование, план, проверки, документы. */
  | 'ответственный'
  /** Смотрит и выгружает. Ничего не меняет, кроме того, как ему показывать. */
  | 'гость';

export const USER_ROLES: readonly UserRole[] = ['администратор', 'ответственный', 'гость'];

/**
 * Право на действие.
 *
 * Права перечислены поимённо, а не выведены из роли в коде: роль — это набор
 * прав, записанный таблицей, и посмотреть, что кому можно, надо в одном месте,
 * а не собирать по условиям, разбросанным по экранам.
 */
export type Permission =
  /** Заводить и править узлы дерева: площадки, цеха, здания, этажи, склады. */
  | 'дерево.править'
  /** Заводить, править и выводить из эксплуатации оборудование. */
  | 'объекты.править'
  /** Вносить записи о проверках и работах в журнал эксплуатации. */
  | 'журнал.вести'
  /** Расставлять оборудование на плане, обводить помещения. */
  | 'план.править'
  /** Загружать и править подложку: поворот, обрезка, стирание, масштаб. */
  | 'подложка.править'
  /** Периодичность регламентных работ и состав проверок. */
  | 'регламенты.править'
  /** Общие настройки программы. */
  | 'настройки.править'
  /** Заводить пользователей, менять роли, выдавать и забирать доступы. */
  | 'пользователи.править'
  /** Смотреть журнал вносимых изменений. */
  | 'изменения.смотреть'
  /** Подписывать простой электронной подписью. */
  | 'подпись.ставить'
  /** Выгружать журналы, планы, справки и заявки. */
  | 'выгрузка'
  /** Настройки показа: отбор, масштаб, круги покрытия, состав дашборда. */
  | 'отображение';

/**
 * Что кому можно — таблицей.
 *
 * Требования к ролям — такие же данные, как нормы ППР, и записаны так же
 * (AGENTS.md, правило 9). Добавить право или сдвинуть его между ролями здесь —
 * одна строка; в коде, разбросанном по условиям, это была бы ревизия всей
 * программы.
 */
export const ROLE_PERMISSIONS: Readonly<Record<UserRole, readonly Permission[]>> = {
  администратор: [
    'дерево.править', 'объекты.править', 'журнал.вести', 'план.править', 'подложка.править',
    'регламенты.править', 'настройки.править', 'пользователи.править', 'изменения.смотреть',
    'подпись.ставить', 'выгрузка', 'отображение',
  ],
  /*
   * Ответственный ведёт объект, но не задаёт правил.
   *
   * Нет «регламенты.править»: периодичность проверок — требование норматива и
   * решение организации, одно на всех. Если бы её мог сдвинуть каждый
   * ответственный, сроки на соседних зданиях разошлись бы, и журнал перестал
   * бы что-либо значить.
   *
   * Нет «настройки.править» по той же причине.
   *
   * «изменения.смотреть» есть: это чтение, и смотреть он сможет только свои
   * объекты — область прав ограничивает и журнал изменений тоже.
   */
  ответственный: [
    'дерево.править', 'объекты.править', 'журнал.вести', 'план.править', 'подложка.править',
    'изменения.смотреть', 'подпись.ставить', 'выгрузка', 'отображение',
  ],
  /*
   * Гость смотрит и выгружает.
   *
   * «подпись.ставить» ему не выдаётся: подпись — это принятие ответственности
   * за содержание записи, а гость за него не отвечает и менять его не может.
   */
  гость: ['выгрузка', 'отображение'],
};

/**
 * Отпечаток пароля.
 *
 * Сам пароль не хранится — ни в открытом виде, ни зашифрованным. Хранится
 * результат медленной функции с солью: подобрать по нему пароль дорого, а
 * проверить введённый — быстро.
 *
 * Параметры записаны рядом с отпечатком, а не заданы в коде: когда их придётся
 * ужесточить, старые отпечатки должны остаться проверяемыми.
 */
export interface PasswordDigest {
  readonly algorithm: 'scrypt';
  /** Соль, base64. Своя у каждого пользователя и у каждой смены пароля. */
  readonly salt: string;
  /** Отпечаток, base64. */
  readonly digest: string;
  readonly costN: number;
  readonly blockSizeR: number;
  readonly parallelP: number;
  readonly keyLength: number;
}

export interface UserAccount {
  readonly id: UserId;
  /** Имя для входа. Уникально, сравнивается без учёта регистра. */
  readonly login: string;
  /** ФИО. Подставляется исполнителем работ и попадает в подпись. */
  readonly fullName: string;
  readonly position: string | null;
  /**
   * Организация, в которой человек работает.
   *
   * Заказчик: «в личном кабинете и при создании аккаунта пользователь должен
   * добавить ФИО, должность и организацию, где работает; потом эта информация
   * подставляется в соответствующие графы при проверке оборудования».
   *
   * Это не организация из дерева объекта. Дерево отвечает на вопрос «чьё
   * оборудование», а здесь — «от кого пришёл человек». Чаще всего это одно и
   * то же, но подрядчик, который обслуживает установку по договору, работает в
   * своей организации, и в акте должна стоять она.
   */
  readonly organization: string | null;
  /** Почта для связи и для привязки учётной записи. Не обязательна. */
  readonly email: string | null;
  readonly role: UserRole;
  /**
   * Узлы дерева, порученные пользователю. Права идут вниз: выдали цех —
   * доступны все его здания, этажи и склады.
   *
   * У администратора список не смотрится: ему доступно всё. У гостя —
   * смотрится: он видит то, что ему открыли, и ничего сверх этого.
   */
  readonly scope: readonly TreeNodeId[];
  /** Отпечаток пароля. null — пароль ещё не задан: первый вход. */
  readonly password: PasswordDigest | null;
  /**
   * Поколение ключа: растёт при каждой смене пароля.
   *
   * Нужно подписи: она запоминает, каким поколением ключа была поставлена.
   * Смена пароля прежние подписи не отменяет — они привязаны к учётной записи,
   * а не к паролю, — но по поколению видно, тем же ключом подписано или уже
   * другим.
   */
  readonly keyGeneration: number;
  /**
   * Ключ простой электронной подписи: открытый и зашифрованный закрытый.
   *
   * `null` — ключа ещё нет: учётная запись заведена, но пароль не задан
   * самим человеком. Подписывать нечем, и это правильно: ключ, созданный
   * под временный пароль администратора, знали бы двое.
   */
  readonly signingKey?: SigningKey | null;
  /** Пароль задан администратором и должен быть заменён при первом входе. */
  readonly mustChangePassword: boolean;
  /**
   * Редакция принятых соглашений — дата в виде ГГГГ-ММ-ДД, либо пусто.
   *
   * Записывается версия, а не признак согласия: текст соглашения со временем
   * меняется, и без версии через год нельзя ни показать принятую редакцию,
   * ни понять, требуется ли принять новую.
   */
  readonly acceptedLegalVersion?: string | null;
  /** Когда приняты соглашения этой редакции. */
  readonly acceptedLegalAt?: IsoDateTime | null;
  /** Учётная запись отключена. Записи и подписи остаются: их автор не исчезает. */
  readonly archivedAt: IsoDateTime | null;
  readonly createdAt: IsoDateTime;
  readonly updatedAt: IsoDateTime;
  readonly rowVersion: number;
}

/** Кто работает сейчас. Собирается при входе и живёт до закрытия программы. */
export interface Session {
  readonly user: UserAccount;
  readonly startedAt: IsoDateTime;
}

export interface UserRepository {
  list(): Promise<Result<readonly UserAccount[]>>;
  getById(id: UserId): Promise<Result<UserAccount>>;
  /** Поиск для входа. Регистр имени не важен. null — такого имени нет. */
  findByLogin(login: string): Promise<Result<UserAccount | null>>;
  save(user: UserAccount): Promise<Result<void>>;
  /**
   * Удаляет учётную запись совсем.
   *
   * Единственное физическое удаление среди хранилищ данных — и оно
   * ограничено правилом: удаляют лишь того, кто ничего не подписывал
   * (см. `userDeletionCheck`). Подпись определяет подписавшего, и
   * запись «подписал тот, кого в программе нет» этому не отвечает.
   */
  remove(id: UserId): Promise<Result<void>>;
}

/**
 * Считает отпечатки паролей и содержимого.
 *
 * Порт, а не готовая реализация: считать нужно в основном процессе, где есть
 * настоящая криптография, а сценарии ядра должны оставаться независимыми от
 * того, где они выполняются.
 */
export interface PasswordHasher {
  hash(password: string): Promise<Result<PasswordDigest>>;
  verify(password: string, digest: PasswordDigest): Promise<Result<boolean>>;
  /** SHA-256 текста в шестнадцатеричном виде — отпечаток подписанного содержимого. */
  sha256Hex(text: string): Promise<Result<string>>;
}
