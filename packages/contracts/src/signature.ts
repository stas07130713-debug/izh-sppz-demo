/**
 * Простая электронная подпись (63-ФЗ «Об электронной подписи»).
 *
 * По статье 5 части 2 простая электронная подпись — та, которая посредством
 * кодов, паролей или иных средств подтверждает факт формирования подписи
 * определённым лицом. Здесь таким средством служит пароль учётной записи:
 * подписать может только тот, кто его знает, а знает его только он сам —
 * хранится лишь отпечаток.
 *
 * По статье 9 части 1 документ считается подписанным простой электронной
 * подписью, если подпись содержится в самом документе. Поэтому подпись
 * хранится внутри подписанной записи, а не отдельным списком где-то рядом.
 *
 * По статье 9 части 2 равнозначность собственноручной подписи возникает не
 * сама собой: нужен нормативный акт или соглашение участников, где записаны
 * правила определения подписавшего и обязанность хранить ключ в тайне. Такой
 * документ издаёт организация, а программа хранит его реквизиты в поле basis и
 * показывает их вместе с подписью. Без реквизитов подпись остаётся отметкой
 * «кто и когда подтвердил» — полезной, но не равнозначной собственноручной.
 *
 * Что именно подписывается (по требованию заказчика):
 *
 *  - результаты проверок и работ — записи журнала эксплуатации систем
 *    противопожарной защиты, который ведут по пункту 17 ППР РФ № 1479;
 *  - журнал при выгрузке на печать — подписывается сформированный файл целиком.
 *
 * Отпечаток содержимого нужен именно для второго: подпись под журналом должна
 * относиться к тому, что напечатано, а не к «журналу вообще». Пересчитали
 * отпечаток, сверили с записанным — видно, тот же это документ или уже другой.
 */

import type { IsoDateTime } from './basic-types.js';
import type { UserId, UserRole } from './access.js';
import type { KeySignature } from './signing-key.js';

/** Что подписано. Разные виды подписываемого — разные требования к содержимому. */
export type SignedKind =
  /** Запись журнала эксплуатации: результат проверки, ТО, перезарядки. */
  | 'запись журнала'
  /** Выгруженный журнал: файл, который печатают и предъявляют. */
  | 'журнал на печать'
  /**
   * Заведение оборудования в журнал: появление новой строки.
   *
   * Заказчик: «при заведении нового огнетушителя или элемента, и вообще при
   * создании новых строк в журнале должна ставиться ПЭП».
   *
   * Это не проверка и не работа: подписывается не «что сделано с предметом», а
   * «кто внёс предмет в журнал и за какие сведения о нём отвечает». Отдельный
   * вид намеренно — иначе заведение читалось бы как выполненная работа,
   * которой не было.
   */
  | 'заведение в журнал';

export interface SimpleSignature {
  readonly signerId: UserId;
  /**
   * ФИО, должность и роль на момент подписания — снимок, а не ссылка.
   *
   * Человек меняет должность и уходит из организации, а подпись под прошлогодней
   * проверкой должна и через год говорить, кем он был тогда. Ссылка на учётную
   * запись показала бы сегодняшнюю должность под вчерашней записью.
   */
  readonly signerName: string;
  readonly signerPosition: string | null;
  readonly signerRole: UserRole;
  readonly signedAt: IsoDateTime;
  readonly kind: SignedKind;
  /** SHA-256 подписанного содержимого, шестнадцатеричный. */
  readonly contentHash: string;
  /** Поколение ключа: каким паролем подписано. Смена пароля подпись не отменяет. */
  readonly keyGeneration: number;
  /**
   * Основание: реквизиты документа организации о применении простой
   * электронной подписи. Пусто — документа нет, и равнозначности
   * собственноручной подписи тоже нет.
   */
  readonly basis: string | null;
  /**
   * Криптографическая часть: подпись отпечатка закрытым ключом подписавшего.
   *
   * Может отсутствовать у подписей, поставленных до появления ключей: они
   * остаются действительными отметками «кто и когда подтвердил», но
   * проверить их можно только внутри программы.
   */
  readonly key?: KeySignature | null;
}

/** Итог сверки подписи с тем, что подписано. */
export type SignatureCheck =
  /** Содержимое то же, каким его подписали. */
  | { readonly verdict: 'подпись верна' }
  /** Содержимое изменилось после подписания. */
  | { readonly verdict: 'содержимое изменено'; readonly expected: string; readonly actual: string }
  /** Подписи нет вовсе. */
  | { readonly verdict: 'не подписано' }
  /**
   * Подпись не подтверждается открытым ключом.
   *
   * Отпечаток содержимого сошёлся, а подпись под ним — нет. Так выглядит
   * подделка: тот, кто правил файл, пересчитал отпечаток, но подписать его
   * закрытым ключом не смог.
   */
  | { readonly verdict: 'подпись не сходится' };
